    @Test
    void fullstackEndpoint_rejectsInvalidPages() {
        assertRejected(p -> p.get(0).put("type", "report"), "type 'report' is not supported yet");
        assertRejected(p -> p.get(0).put("type", "gallery"), "unknown type 'gallery'");
        assertRejected(p -> p.get(0).put("id", "Overview"), "Page id 'Overview' must be lower-case");
        assertRejected(p -> p.get(5).put("id", "overview"), "Duplicate page id 'overview'");
        assertRejected(p -> p.get(5).put("entity", "Customer"), "unknown entity 'Customer'");
        assertRejected(p -> p.get(0).put("entity", "Ticket"), "(dashboard) does not take 'entity'");
        assertRejected(p -> p.get(0).put("widgets", List.of()), "needs at least one widget");
        assertRejected(p -> p.get(0).put("widgets", List.of(Map.of("kind", "bar", "entity", "Ticket", "groupBy", "subject"))),
                "groupBy 'subject' must be a non-key enum or boolean field");
        assertRejected(p -> p.get(0).put("widgets", List.of(Map.of("kind", "bar", "entity", "Team"))),
                "Team has no enum or boolean field to group by");
        assertRejected(p -> p.get(0).put("widgets", List.of(Map.of("kind", "kpi", "entity", "Ticket", "agg", "sum"))),
                "agg 'sum' is not supported yet");
        assertRejected(p -> p.get(0).put("widgets", List.of(Map.of("kind", "recent", "entity", "Ticket", "limit", 99))),
                "limit must be between 1 and 20");
        assertRejected(p -> p.get(1).put("tabs", List.of(Map.of("page", "tickets-open"))), "needs between 2 and 6 tabs");
        assertRejected(p -> p.get(1).put("tabs", List.of(Map.of("page", "tickets-open"), Map.of("page", "queue"))),
                "a tab cannot embed another tabs page ('queue')");
        assertRejected(p -> p.get(1).put("tabs", List.of(Map.of("page", "tickets-open"), Map.of("page", "nope"))),
                "no page with id 'nope'");
        assertRejected(p -> p.get(1).remove("title"), "Page 'queue' (tabs) needs a title");
        assertRejected(p -> p.get(2).put("presetFilter", Map.of("status", "LOST")), "'LOST' is not one of");
        assertRejected(p -> p.get(2).put("presetFilter", Map.of("subject", "x")),
                "only filterable enum or boolean fields can be preset");
        assertRejected(p -> p.forEach(page -> page.put("hidden", true)), "At least one page must be visible");
        // Master-detail
        assertRejected(p -> p.get(6).put("parent", "Ticket"), "Page 'teams' (master-detail): Ticket has no relation to Ticket");
        assertRejected(p -> p.get(6).put("via", "assignee"), "via 'assignee' is not a relation of Ticket to Team");
        assertRejected(p -> p.get(6).remove("child"), "Page 'teams' (master-detail) child: entity is required");
        assertRejected(p -> p.get(6).put("entity", "Team"), "(master-detail) does not take 'entity'");
        assertRejected(p -> p.get(5).put("parent", "Team"), "(entity-list) does not take 'parent'");
        // Record
        assertRejected(p -> p.add(recordPage("ticket", "Ticket", false)), "cannot be in the navigation");
        assertRejected(p -> {
            p.add(recordPage("ticket", "Ticket", null));
            p.add(recordPage("ticket-again", "Ticket", null));
        }, "Ticket already has a record page ('ticket')");
        assertRejected(p -> {
            p.add(recordPage("ticket", "Ticket", null));
            p.get(1).put("tabs", List.of(Map.of("page", "tickets-open"), Map.of("page", "ticket")));
        }, "a tab cannot embed a record page ('ticket')");
        assertRejected(p -> {
            Map<String, Object> page = recordPage("team", "Team", null);
            page.put("childTabs", List.of("Ticket", "Ticket"));
            p.add(page);
        }, "Ticket is already a tab");
        assertRejected(p -> {
            Map<String, Object> page = recordPage("ticket", "Ticket", null);
            page.put("childTabs", List.of("Team"));
            p.add(page);
        }, "Team has no relation to Ticket");
        assertRejected(p -> p.get(0).put("childTabs", List.of("Team")), "(dashboard) does not take 'childTabs'");
    }

    @Test
    void fullstackEndpoint_rejectsAmbiguousOrCompositeKeyLayouts() {
        Map<String, Object> ambiguous = withTicketReporter(exampleBody("tickets", "react-tailwind-crud"));
        pages(ambiguous).add(new LinkedHashMap<>(Map.of("id", "by-agent", "type", "master-detail",
                "parent", "Agent", "child", "Ticket")));
        assertBadRequest(ambiguous, "Ticket has several relations to Agent [assignee, reporter]; set 'via' to pick one");

        Map<String, Object> composite = exampleBody("tickets", "react-tailwind-crud");
        entities(composite).add(new LinkedHashMap<>(Map.of("name", "Shift", "fields", List.of(
                Map.of("name", "agentCode", "type", "STRING", "primaryKey", true),
                Map.of("name", "day", "type", "LOCAL_DATE", "primaryKey", true)))));
        pages(composite).add(recordPage("shift", "Shift", null));
        assertBadRequest(composite, "Shift has a composite key; only single-key entities can be opened as one record");
    }


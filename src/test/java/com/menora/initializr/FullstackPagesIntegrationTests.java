    // ── Helpers ─────────────────────────────────────────────────────────────

    private void assertRejected(Consumer<List<Map<String, Object>>> mutator, String expectedMessage) {
        Map<String, Object> body = exampleBody("tickets", "react-tailwind-crud");
        mutator.accept(pages(body));
        assertBadRequest(body, expectedMessage);
    }

    private void assertBadRequest(Map<String, Object> body, String expectedMessage) {
        ResponseEntity<String> response = restTemplate.exchange("/starter-fullstack.zip", HttpMethod.POST,
                new HttpEntity<>(body, jsonHeaders()), String.class);
        assertThat(response.getStatusCode()).as(expectedMessage).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(response.getBody()).contains(expectedMessage);
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> pages(Map<String, Object> body) {
        return (List<Map<String, Object>>) body.get("pages");
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> entities(Map<String, Object> body) {
        return (List<Map<String, Object>>) body.get("entities");
    }

    private static Map<String, Object> recordPage(String id, String entity, Boolean hidden) {
        Map<String, Object> page = new LinkedHashMap<>(Map.of("id", id, "type", "record", "entity", entity));
        if (hidden != null) page.put("hidden", hidden);
        return page;
    }

    /** Gives Ticket a second relation to Agent, so Agent → Ticket is ambiguous without {@code via}. */
    @SuppressWarnings("unchecked")
    private static Map<String, Object> withTicketReporter(Map<String, Object> body) {
        List<Map<String, Object>> entities = entities(body);
        for (int i = 0; i < entities.size(); i++) {
            if (!"Ticket".equals(entities.get(i).get("name"))) continue;
            Map<String, Object> ticket = new LinkedHashMap<>(entities.get(i));
            List<Object> relations = new ArrayList<>((List<Object>) ticket.get("relations"));
            relations.add(Map.of("type", "MANY_TO_ONE", "fieldName", "reporter", "targetEntity", "Agent"));
            ticket.put("relations", relations);
            entities.set(i, ticket);
        }
        return body;
    }

    /** A fullstack request built from a seeded example's entities + pages (mutable copies). */
    static Map<String, Object> exampleBody(String exampleId, String frontendSet) {
        try (InputStream in = new ClassPathResource("catalog/fullstack-examples.json").getInputStream()) {
            List<Map<String, Object>> examples = new ObjectMapper().readValue(in, new TypeReference<>() {});
            Map<String, Object> example = examples.stream()
                    .filter(e -> exampleId.equals(e.get("exampleId"))).findFirst().orElseThrow();
            Map<String, Object> body = new LinkedHashMap<>();
            body.put("artifactId", "support");
            body.put("packageName", "com.menora.support");
            body.put("bootVersion", "3.2.1");
            body.put("frontendTemplateSet", frontendSet);
            body.put("entities", new ArrayList<>((List<Map<String, Object>>) example.get("entities")));
            body.put("pages", new ArrayList<>(example.get("pages") == null ? List.of()
                    : ((List<Map<String, Object>>) example.get("pages")).stream()
                            .map(p -> (Map<String, Object>) new LinkedHashMap<>(p)).toList()));
            return body;
        } catch (java.io.IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private Map<String, String> generate(Map<String, Object> body) throws Exception {
        ResponseEntity<byte[]> response = restTemplate.exchange("/starter-fullstack.zip", HttpMethod.POST,
                new HttpEntity<>(body, jsonHeaders()), byte[].class);
        assertThat(response.getStatusCode())
                .as(response.getBody() == null ? "" : new String(response.getBody(), StandardCharsets.UTF_8))
                .isEqualTo(HttpStatus.OK);
        Map<String, String> result = new TreeMap<>();
        try (ZipInputStream zin = new ZipInputStream(new ByteArrayInputStream(response.getBody()))) {
            ZipEntry entry;
            while ((entry = zin.getNextEntry()) != null) {
                if (entry.isDirectory()) continue;
                ByteArrayOutputStream out = new ByteArrayOutputStream();
                zin.transferTo(out);
                result.put(entry.getName(), out.toString(StandardCharsets.UTF_8));
            }
        }
        return result;
    }

    private static HttpHeaders jsonHeaders() {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        return headers;
    }

package com.menora.initializr;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.context.annotation.Import;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Golden per-file hashes of the whole fullstack zip for every seeded example, on both frontend
 * sets, in English and in Hebrew/RTL, with the example's layout and in the classic shell.
 *
 * <p>The design-kit work (see {@code DESIGN_STUDIO_PLAN.md} at the monorepo root) reshapes the
 * templates in deliberate commits and then requires the kit path to reproduce the legacy bytes.
 * These manifests make every byte change visible in review: a template edit that changes output
 * fails here, naming each added, removed and changed file per case. Content is hashed after
 * {@code \r\n} → {@code \n}, because a Windows checkout renders CRLF templates and CI does not.
 *
 * <p>After an intended change, regenerate with
 * {@code mvn test -Dtest=FullstackGoldenOutputTests -Dgolden.update=true} and review the
 * {@code src/test/resources/golden/fullstack/*.sha} diff.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@Import(TestInvokerConfiguration.class)
class FullstackGoldenOutputTests {

    private static final Path GOLDEN_DIR = Path.of("src", "test", "resources", "golden", "fullstack");
    private static final List<String> FRONTEND_SETS = List.of("react-tailwind-crud", "react-menora-digital-crud");
    private static final boolean UPDATE = Boolean.getBoolean("golden.update");

    @Autowired
    private TestRestTemplate restTemplate;

    @Test
    void everyExampleGeneratesItsPinnedBytes() throws Exception {
        List<String> failures = new ArrayList<>();
        Set<String> written = new TreeSet<>();
        for (Map<String, Object> example : FullstackExampleRequests.examples()) {
            boolean hasPages = FullstackExampleRequests.hasPages(example);
            for (String set : FRONTEND_SETS) {
                for (String locale : List.of("en", "he")) {
                    for (boolean layout : hasPages ? List.of(true, false) : List.of(false)) {
                        String name = example.get("exampleId") + "__" + set + "__" + locale
                                + "__" + (layout ? "layout" : "classic");
                        Map<String, String> actual = hashes(generate(FullstackExampleRequests.body(example, set, locale, layout)));
                        Path golden = GOLDEN_DIR.resolve(name + ".sha");
                        written.add(golden.getFileName().toString());
                        if (UPDATE) {
                            Files.createDirectories(GOLDEN_DIR);
                            Files.writeString(golden, format(actual), StandardCharsets.UTF_8);
                        } else if (!Files.exists(golden)) {
                            failures.add(name + ": no golden manifest (run with -Dgolden.update=true)");
                        } else {
                            String diff = diff(parse(Files.readString(golden, StandardCharsets.UTF_8)), actual);
                            if (!diff.isEmpty()) failures.add(name + ":\n" + diff);
                        }
                    }
                }
            }
        }
        if (UPDATE) {
            // Drop manifests for cases that no longer exist (an example removed or renamed).
            try (var files = Files.list(GOLDEN_DIR)) {
                for (Path stale : files.filter(f -> !written.contains(f.getFileName().toString())).toList()) {
                    Files.delete(stale);
                }
            }
        }
        assertThat(failures).as("Generated bytes differ from the golden manifests. If the change is intended, "
                + "re-run with -Dgolden.update=true and review the diff.\n" + String.join("\n", failures)).isEmpty();
    }

    /** Generation is deterministic, or a golden hash would be meaningless. */
    @Test
    void generationIsDeterministic() throws Exception {
        Map<String, Object> example = FullstackExampleRequests.examples().stream()
                .filter(e -> "approvals".equals(e.get("exampleId"))).findFirst().orElseThrow();
        Map<String, Object> body = FullstackExampleRequests.body(example, "react-menora-digital-crud", "he", true);
        assertThat(hashes(generate(body))).isEqualTo(hashes(generate(body)));
    }

    private Map<String, byte[]> generate(Map<String, Object> body) throws IOException {
        ResponseEntity<byte[]> response = FullstackExampleRequests.post(restTemplate, body);
        assertThat(response.getStatusCode())
                .as(response.getBody() == null ? "" : new String(response.getBody(), StandardCharsets.UTF_8))
                .isEqualTo(HttpStatus.OK);
        return FullstackExampleRequests.unzip(response.getBody());
    }

    /** sha256 per path; text has its line endings normalized, binaries are hashed as they are. */
    private static Map<String, String> hashes(Map<String, byte[]> files) throws Exception {
        Map<String, String> result = new TreeMap<>();
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            byte[] bytes = e.getValue();
            if (isText(bytes)) {
                bytes = new String(bytes, StandardCharsets.UTF_8).replace("\r\n", "\n").getBytes(StandardCharsets.UTF_8);
            }
            result.put(e.getKey(), HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)));
        }
        return result;
    }

    private static boolean isText(byte[] bytes) {
        for (byte b : bytes) if (b == 0) return false;
        return true;
    }

    private static String format(Map<String, String> hashes) {
        StringBuilder out = new StringBuilder();
        hashes.forEach((path, sha) -> out.append(sha).append("  ").append(path).append('\n'));
        return out.toString();
    }

    private static Map<String, String> parse(String manifest) {
        Map<String, String> result = new TreeMap<>();
        for (String line : manifest.replace("\r\n", "\n").split("\n")) {
            if (line.isBlank()) continue;
            int sep = line.indexOf("  ");
            result.put(line.substring(sep + 2), line.substring(0, sep));
        }
        return result;
    }

    private static String diff(Map<String, String> expected, Map<String, String> actual) {
        StringBuilder out = new StringBuilder();
        Set<String> paths = new TreeSet<>(expected.keySet());
        paths.addAll(actual.keySet());
        for (String path : paths) {
            String was = expected.get(path);
            String is = actual.get(path);
            if (was == null) out.append("  + ").append(path).append('\n');
            else if (is == null) out.append("  - ").append(path).append('\n');
            else if (!was.equals(is)) out.append("  ~ ").append(path).append('\n');
        }
        return out.toString();
    }
}

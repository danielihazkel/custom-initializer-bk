package com.menora.initializr;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.function.BinaryOperator;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Golden per-file hashes of generated projects: one manifest ({@code <case>.sha}, a sha256 per
 * file) per case under {@code src/test/resources/golden/<group>/}.
 *
 * <p>A manifest makes every byte change visible in review. A case whose generated files differ
 * from its manifest is reported with each added ({@code +}), removed ({@code -}) and changed
 * ({@code ~}) file, and its files are written under {@code target/golden-actual/} so they can be
 * diffed. Text is hashed after {@code \r\n} → {@code \n}, because a Windows checkout renders CRLF
 * templates and CI does not.
 *
 * <p>After an intended change, run the suite with {@code -Dgolden.update=true} and review the
 * {@code .sha} diff: it is the list of files the change reaches.
 */
final class GoldenManifests {

    static final boolean UPDATE = Boolean.getBoolean("golden.update");

    private final Path goldenDir;
    private final Path actualDir;
    /** Rewrites a text file before hashing — (path, text) → text — to mask what legitimately varies. */
    private final BinaryOperator<String> mask;
    private final List<String> failures = new ArrayList<>();
    private final Set<String> written = new TreeSet<>();

    /**
     * @param group     the manifests' folder under {@code src/test/resources/golden/}
     * @param actualDir where a failing case's files are written for diffing
     * @param mask      rewrites a text file before it is hashed, or returns it as it is
     */
    GoldenManifests(String group, Path actualDir, BinaryOperator<String> mask) {
        this.goldenDir = Path.of("src", "test", "resources", "golden", group);
        this.actualDir = actualDir;
        this.mask = mask;
    }

    /** Compares one case's files with — or, updating, writes — its manifest. */
    void pin(String name, Map<String, byte[]> files) throws Exception {
        Map<String, String> actual = hashes(files);
        Path golden = goldenDir.resolve(name + ".sha");
        written.add(golden.getFileName().toString());
        if (UPDATE) {
            Files.createDirectories(goldenDir);
            Files.writeString(golden, format(actual), StandardCharsets.UTF_8);
        } else if (!Files.exists(golden)) {
            failures.add(name + ": no golden manifest (run with -Dgolden.update=true)");
        } else {
            String diff = diff(parse(Files.readString(golden, StandardCharsets.UTF_8)), actual);
            if (!diff.isEmpty()) {
                failures.add(name + ":\n" + diff + "  (generated files: " + dump(name, files) + ")");
            }
        }
    }

    /**
     * Ends a run over every case of the group: updating, drops the manifests of cases that no
     * longer exist; otherwise fails with what differs.
     */
    void finish() throws IOException {
        if (UPDATE && Files.isDirectory(goldenDir)) {
            try (var files = Files.list(goldenDir)) {
                for (Path stale : files.filter(f -> !written.contains(f.getFileName().toString())).toList()) {
                    Files.delete(stale);
                }
            }
        }
        assertThat(failures).as("Generated bytes differ from the golden manifests. If the change is intended, "
                + "re-run with -Dgolden.update=true and review the diff.\n" + String.join("\n", failures)).isEmpty();
    }

    /** sha256 per path; text has its line endings normalized and is masked, binaries are hashed as they are. */
    Map<String, String> hashes(Map<String, byte[]> files) throws Exception {
        Map<String, String> result = new TreeMap<>();
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            byte[] bytes = e.getValue();
            if (isText(bytes)) {
                String text = new String(bytes, StandardCharsets.UTF_8).replace("\r\n", "\n");
                bytes = mask.apply(e.getKey(), text).getBytes(StandardCharsets.UTF_8);
            }
            result.put(e.getKey(), HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)));
        }
        return result;
    }

    /**
     * Writes a failing case's files under the actual directory, text with LF line endings — the
     * manifests hold only hashes, so this is what a changed file is diffed against (generate the
     * same case on the previous commit and compare the two trees).
     */
    private Path dump(String name, Map<String, byte[]> files) throws IOException {
        Path root = actualDir.resolve(name);
        org.springframework.util.FileSystemUtils.deleteRecursively(root);
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            Path file = root.resolve(e.getKey()).normalize();
            if (!file.startsWith(root)) continue;
            Files.createDirectories(file.getParent());
            byte[] bytes = e.getValue();
            if (isText(bytes)) {
                bytes = new String(bytes, StandardCharsets.UTF_8).replace("\r\n", "\n").getBytes(StandardCharsets.UTF_8);
            }
            Files.write(file, bytes);
        }
        return root;
    }

    private static boolean isText(byte[] bytes) {
        for (byte b : bytes) if (b == 0) return false;
        return true;
    }

    private static String format(Map<String, String> hashes) {
        StringBuilder out = new StringBuilder();
        hashes.forEach((path, sha) -> out.append(sha).append("  ").append(path).append('\n'));
        return out.toString();
    }

    private static Map<String, String> parse(String manifest) {
        Map<String, String> result = new TreeMap<>();
        for (String line : manifest.replace("\r\n", "\n").split("\n")) {
            if (line.isBlank()) continue;
            int sep = line.indexOf("  ");
            result.put(line.substring(sep + 2), line.substring(0, sep));
        }
        return result;
    }

    private static String diff(Map<String, String> expected, Map<String, String> actual) {
        StringBuilder out = new StringBuilder();
        Set<String> paths = new TreeSet<>(expected.keySet());
        paths.addAll(actual.keySet());
        for (String path : paths) {
            String was = expected.get(path);
            String is = actual.get(path);
            if (was == null) out.append("  + ").append(path).append('\n');
            else if (is == null) out.append("  - ").append(path).append('\n');
            else if (!was.equals(is)) out.append("  ~ ").append(path).append('\n');
        }
        return out.toString();
    }
}

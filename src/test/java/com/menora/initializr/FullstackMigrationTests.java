package com.menora.initializr;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * A fullstack project with Flyway on its build gets its schema as the first migration, and an
 * update of such a project gets what the model changed as a migration of its own.
 *
 * <p>What is asserted here is text. That the schema is the one the generated entities expect is
 * proved by building: {@code GeneratedBackendBuildSmokeTests.flywayBaselineIsTheSchemaTheEntitiesExpect}
 * starts generated backends on it with {@code ddl-auto: validate}.
 */
@IntegrationTest
class FullstackMigrationTests {

    private static final String RESOURCES = "press/backend/src/main/resources/";
    private static final String BASELINE = RESOURCES + "db/migration/V1__init.sql";

    @Autowired
    private TestRestTemplate rest;

    /** Posts, their author (many-to-one) and their tags (many-to-many), on the given dependencies. */
    static Map<String, Object> press(String... dependencies) {
        Map<String, Object> body = FullstackExampleRequests.manyToManyBody("react-tailwind-crud");
        body.put("dependencies", List.of(dependencies));
        return body;
    }

    private Map<String, byte[]> generate(Map<String, Object> body) throws Exception {
        ResponseEntity<byte[]> response = FullstackExampleRequests.post(rest, body);
        assertThat(response.getStatusCode())
                .as(response.getBody() == null ? "" : new String(response.getBody(), StandardCharsets.UTF_8))
                .isEqualTo(HttpStatus.OK);
        return FullstackExampleRequests.unzip(response.getBody());
    }

    private static String text(Map<String, byte[]> files, String path) {
        assertThat(files).containsKey(path);
        return new String(files.get(path), StandardCharsets.UTF_8);
    }

    @Test
    void withFlywayTheEntityModelIsTheFirstMigration() throws Exception {
        Map<String, byte[]> files = generate(press("web", "data-jpa", "h2", "validation", "flyway"));
        String sql = text(files, BASELINE);

        assertThat(sql)
                .startsWith("-- The schema of this project's entities")
                .contains("for H2.")
                // The dependency's placeholder is gone.
                .doesNotContain("app_metadata")
                .contains("create table authors (\n    id bigint generated by default as identity not null,")
                .contains("create table tags (")
                .contains("create table posts (")
                .contains("constraint pk_posts primary key (id)")
                // The many-to-one: a column, a foreign key and an index on it.
                .contains("    author_id bigint")
                .contains("alter table posts add constraint fk_posts_author_id foreign key (author_id) references authors (id);")
                .contains("create index ix_posts_author_id on posts (author_id);")
                // The many-to-many: its join table, keyed by both columns.
                .contains("create table post_tags (\n    post_id bigint not null,\n    tag_id bigint not null,\n"
                        + "    constraint pk_post_tags primary key (post_id, tag_id)\n);")
                .contains("alter table post_tags add constraint fk_post_tags_post_id foreign key (post_id) references posts (id);")
                .contains("alter table post_tags add constraint fk_post_tags_tag_id foreign key (tag_id) references tags (id);")
                .contains("create index ix_post_tags_tag_id on post_tags (tag_id);");
        // The audit option of this model: both timestamps on every table that takes them.
        assertThat(sql).contains("created_at timestamp(6) with time zone").contains("updated_at timestamp(6) with time zone");

        // Hibernate checks the schema the migration made; it does not make one beside it.
        assertThat(text(files, RESOURCES + "application.yaml")).contains("ddl-auto: validate").doesNotContain("create-drop");
    }

    @Test
    void theMigrationIsWrittenForTheProjectsDatabase() throws Exception {
        // A project that names PostgreSQL runs on it, whatever else it has for its tests.
        String postgres = text(generate(press("web", "data-jpa", "postgresql", "h2", "validation", "flyway")), BASELINE);
        assertThat(postgres).contains("for PostgreSQL.")
                .contains("id bigint generated by default as identity not null");

        String oracle = text(generate(press("web", "data-jpa", "oracle", "validation", "flyway")), BASELINE);
        assertThat(oracle).contains("for Oracle.")
                .contains("id number(19,0) generated by default as identity not null")
                .contains("varchar2(255 char)")
                .contains("created_at timestamp(6) with time zone");

        String sqlServer = text(generate(press("web", "data-jpa", "mssql", "validation", "flyway")), BASELINE);
        assertThat(sqlServer).contains("for SQL Server.")
                .contains("id bigint identity not null")
                .contains("created_at datetimeoffset(6)");

        String db2 = text(generate(press("web", "data-jpa", "db2", "validation", "flyway")), BASELINE);
        assertThat(db2).contains("for DB2.")
                .contains("id bigint generated by default as identity not null")
                .contains("created_at timestamp(6)");
    }

    @Test
    void theGeneratorsOwnTablesAreInTheMigration() throws Exception {
        // File and image fields keep their bytes in app_attachment; the column holds its id.
        Map<String, Object> body = FullstackExampleRequests.fieldTypesBody("react-tailwind-crud");
        body.put("dependencies", List.of("web", "data-jpa", "h2", "validation", "flyway"));
        String sql = text(generate(body), "rota/backend/src/main/resources/db/migration/V1__init.sql");
        assertThat(sql)
                .contains("create table app_attachment (\n    id uuid not null,\n    file_name varchar(255) not null,")
                // Who uploaded it; the bytes only with the database storage (a folder or S3 otherwise).
                .contains("    created_by varchar(255),\n    content blob,")
                .contains("ix_app_attachment_created")
                // One column per field type of the model.
                .contains("    starts_at time(6),")
                .contains("    clocked_in timestamp(6) with time zone,")
                .contains("    rate numeric(19,2) not null,")
                .contains("    notes text,")
                .contains("    contract uuid,")
                .contains("    photo uuid not null,")
                .contains("    status varchar(255),");
    }

    @Test
    void withoutFlywayNothingChanges() throws Exception {
        Map<String, byte[]> files = generate(press("web", "data-jpa", "h2", "validation"));
        assertThat(files.keySet()).noneMatch(path -> path.contains("db/migration"));
        assertThat(text(files, RESOURCES + "application.yaml")).contains("ddl-auto: create-drop");
    }

    // ── Updating a project ───────────────────────────────────────────────────

    /** The same project after the model moved on: tags are gone, posts have a category and two new fields. */
    @SuppressWarnings("unchecked")
    static Map<String, Object> changed(Map<String, Object> base) {
        Map<String, Object> body = new LinkedHashMap<>(base);
        List<Map<String, Object>> entities = new ArrayList<>((List<Map<String, Object>>) body.get("entities"));
        Map<String, Object> id = Map.of("name", "id", "type", "LONG", "primaryKey", true, "generated", true);
        Map<String, Object> category = new LinkedHashMap<>();
        category.put("name", "Category");
        category.put("fields", List.of(id, Map.of("name", "name", "type", "STRING", "required", true)));
        Map<String, Object> post = new LinkedHashMap<>(entities.get(2));
        post.put("fields", List.of(id, Map.of("name", "title", "type", "STRING", "required", true),
                Map.of("name", "summary", "type", "STRING"),
                Map.of("name", "slug", "type", "STRING", "required", true, "length", 80)));
        post.put("relations", List.of(
                Map.of("type", "MANY_TO_ONE", "fieldName", "author", "targetEntity", "Author"),
                Map.of("type", "MANY_TO_ONE", "fieldName", "category", "targetEntity", "Category")));
        body.put("entities", List.of(entities.get(0), category, post));
        return body;
    }

    private Map<String, byte[]> update(Map<String, Object> base, Map<String, Object> target) throws Exception {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        ResponseEntity<byte[]> response = rest.exchange("/starter-fullstack.patch", HttpMethod.POST,
                new HttpEntity<>(Map.of("base", base, "target", target), headers), byte[].class);
        assertThat(response.getStatusCode())
                .as(response.getBody() == null ? "" : new String(response.getBody(), StandardCharsets.UTF_8))
                .isEqualTo(HttpStatus.OK);
        return FullstackExampleRequests.unzip(response.getBody());
    }

    @Test
    void anUpdateCarriesWhatTheModelChangedAsAMigrationOfItsOwn() throws Exception {
        Map<String, Object> base = press("web", "data-jpa", "postgresql", "validation", "flyway");
        Map<String, byte[]> zip = update(base, changed(base));

        // The first migration has run: it is not in the update at all.
        assertThat(zip.keySet()).noneMatch(path -> path.endsWith("V1__init.sql"));
        assertThat(text(zip, "press-update/update.patch")).doesNotContain("V1__init.sql");

        // What changed is a new file, named by when it was generated.
        List<String> migrations = zip.keySet().stream()
                .filter(path -> path.matches("press-update/files/backend/src/main/resources/db/migration/V\\d{14}__model_update\\.sql"))
                .toList();
        assertThat(migrations).hasSize(1);
        String sql = text(zip, migrations.get(0));
        assertThat(text(zip, "press-update/update.patch")).contains("__model_update.sql\nnew file mode 100644");

        int review = sql.indexOf("-- ── To review ");
        assertThat(review).isPositive();
        String live = sql.substring(0, review);
        String toReview = sql.substring(review);

        // What the model adds runs as it is.
        assertThat(live)
                .contains("for PostgreSQL.")
                .contains("create table categories (")
                .contains("\nalter table posts add column summary varchar(255);\n")
                .contains("\nalter table posts add column category_id bigint;\n")
                .contains("\nalter table posts add constraint fk_posts_category_id foreign key (category_id) references categories (id);\n")
                .contains("\ncreate index ix_posts_category_id on posts (category_id);\n")
                // A required field is added without NOT NULL: the table may have rows.
                .contains("\nalter table posts add column slug varchar(80);\n");
        assertThat(live).doesNotContain("drop ");

        // What it removes or tightens is commented out, every line of it.
        assertThat(toReview.lines().skip(1)).allMatch(line -> line.isEmpty() || line.startsWith("--"));
        assertThat(toReview)
                .contains("-- alter table posts alter column slug set not null;")
                .contains("-- drop table tags;")
                .contains("-- drop table post_tags;");
        // The notes are wrapped; their words, with the wrapping taken out.
        assertThat(toReview.replace("\n-- ", " "))
                .contains("posts.slug is required by the model. It was added above without NOT NULL")
                .contains("If the entity was renamed rather than removed, rename the table instead");
    }

    @Test
    void anUpdateThatDoesNotTouchTheSchemaAddsNoMigration() throws Exception {
        Map<String, Object> base = press("web", "data-jpa", "h2", "validation", "flyway");
        Map<String, Object> relabelled = new LinkedHashMap<>(base);
        relabelled.put("dashboardTitle", "Press desk");
        Map<String, byte[]> zip = update(base, relabelled);
        assertThat(zip.keySet()).noneMatch(path -> path.contains("db/migration"));
    }

    /**
     * The generator's own tables move on too: a project whose model file says it was generated
     * with version 1 of them (before the Attachments round) is brought up by its next update, even
     * when the model itself did not change its schema. Its model file names the version.
     */
    @Test
    void anUpdateBringsTheGeneratorsOwnTablesUpFromTheVersionTheProjectHas() throws Exception {
        Map<String, Object> base = FullstackExampleRequests.fieldTypesBody("react-tailwind-crud");
        base.put("dependencies", List.of("web", "data-jpa", "h2", "validation", "flyway"));
        Map<String, Object> relabelled = new LinkedHashMap<>(base);
        relabelled.put("dashboardTitle", "Rota desk");
        String migrations = "rota-update/files/backend/src/main/resources/db/migration/";

        // The version this release writes is in the model file and the zip's header.
        ResponseEntity<byte[]> generated = FullstackExampleRequests.post(rest, base);
        assertThat(generated.getHeaders().getFirst("X-Schema-Version")).isEqualTo("3");
        assertThat(text(FullstackExampleRequests.unzip(generated.getBody()), "rota/menora-model.json"))
                .contains("\"schemaVersion\" : 3");

        // Version 1: the round's columns and indexes, and this one's file-column indexes — they run.
        String fromOne = migrationOf(updateFrom(base, relabelled, 1), migrations);
        assertThat(fromOne).doesNotContain("To review")
                .contains("alter table app_attachment add column created_by varchar(255);")
                .contains("create index ix_app_attachment_created on app_attachment (created_at);")
                .containsPattern("create index ixa_\\w+_photo on \\w+ \\(photo\\);");

        // This release's own version: nothing to bring up.
        assertThat(updateFrom(base, relabelled, 3).keySet()).noneMatch(path -> path.contains("__model_update"));

        // No version (a model file from before them): the attachments table's statements are for review.
        String unknown = migrationOf(update(base, relabelled), migrations);
        int review = unknown.indexOf("-- ── To review ");
        assertThat(review).isPositive();
        assertThat(unknown.substring(0, review)).doesNotContain("app_attachment").containsPattern("create index ixa_\\w+_photo");
        assertThat(unknown.substring(review)).contains("-- alter table app_attachment add column created_by varchar(255);");
    }

    private Map<String, byte[]> updateFrom(Map<String, Object> base, Map<String, Object> target, int schemaVersion) throws Exception {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        ResponseEntity<byte[]> response = rest.exchange("/starter-fullstack.patch", HttpMethod.POST,
                new HttpEntity<>(Map.of("base", base, "target", target, "baseSchemaVersion", schemaVersion), headers), byte[].class);
        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        return FullstackExampleRequests.unzip(response.getBody());
    }

    private static String migrationOf(Map<String, byte[]> zip, String folder) {
        String path = zip.keySet().stream().filter(p -> p.startsWith(folder) && p.endsWith("__model_update.sql"))
                .findFirst().orElseThrow(() -> new AssertionError("no migration in " + zip.keySet()));
        return text(zip, path);
    }

    @Test
    void addingFlywayToAProjectBringsTheWholeSchemaAsItsBaseline() throws Exception {
        // No migration ran before: the baseline is the change. (Flyway's baseline-on-migrate, which
        // the dependency sets, marks it as applied on a database that already has the tables.)
        Map<String, byte[]> zip = update(press("web", "data-jpa", "h2", "validation"),
                press("web", "data-jpa", "h2", "validation", "flyway"));
        assertThat(text(zip, "press-update/files/backend/src/main/resources/db/migration/V1__init.sql"))
                .contains("create table posts (");
        assertThat(zip.keySet()).noneMatch(path -> path.contains("__model_update"));
    }
}

package com.menora.initializr.fullstack.schema;

import com.menora.initializr.fullstack.schema.Schema.Column;
import com.menora.initializr.fullstack.schema.Schema.ColumnType;
import com.menora.initializr.fullstack.schema.Schema.ForeignKey;
import com.menora.initializr.fullstack.schema.Schema.Index;
import com.menora.initializr.fullstack.schema.Schema.Table;
import com.menora.initializr.fullstack.schema.Schema.Unique;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * What a schema is written as ({@link SchemaSql}) and what a change to one is written as
 * ({@link SchemaDiff}): which statements run as they are, and which are left for a person.
 */
class SchemaDiffTest {

    private static final Column ID = new Column("id", ColumnType.BIGINT, null, false, true, false);

    private static Table table(String name, List<Column> columns, List<ForeignKey> fks, List<Unique> uniques, List<Index> indexes) {
        return new Table(null, name, columns, List.of("id"), fks, uniques, indexes);
    }

    private static Table orders(Column... extra) {
        List<Column> columns = new ArrayList<>(List.of(ID, Column.varchar("code", 40, false)));
        columns.addAll(List.of(extra));
        return table("orders", columns, List.of(), List.of(new Unique("uk_orders_code", List.of("code"))), List.of());
    }

    private static Schema schema(Table... tables) {
        return new Schema(List.of(tables));
    }

    /** A note is wrapped at 96 columns; its words are compared with the wrapping taken out. */
    private static String unwrapped(String text) {
        return text.replace("\n-- ", " ");
    }

    @Test
    void aBaselineCreatesTablesThenForeignKeysAndIndexes() {
        Table lines = table("order_lines",
                List.of(ID, Column.of("order_id", ColumnType.BIGINT, false), Column.of("price", ColumnType.MONEY, true),
                        new Column("deleted", ColumnType.BOOLEAN, null, false, false, true)),
                List.of(new ForeignKey("fk_order_lines_order_id", List.of("order_id"), null, "orders", List.of("id"))),
                List.of(), List.of(new Index("ix_order_lines_order_id", List.of("order_id"))));
        String sql = SchemaSql.baseline(schema(lines, orders()), SchemaDialect.POSTGRESQL);

        assertThat(sql).contains("""
                create table order_lines (
                    id bigint generated by default as identity not null,
                    order_id bigint not null,
                    price numeric(19,2),
                    deleted boolean default false not null,
                    constraint pk_order_lines primary key (id)
                );
                """).contains("""
                create table orders (
                    id bigint generated by default as identity not null,
                    code varchar(40) not null,
                    constraint pk_orders primary key (id),
                    constraint uk_orders_code unique (code)
                );
                """);
        // After every table, so one that refers to a later one (or to itself) needs no order.
        assertThat(sql.indexOf("alter table order_lines add constraint fk_order_lines_order_id foreign key (order_id) references orders (id);"))
                .isGreaterThan(sql.indexOf("create table orders"));
        assertThat(sql).contains("create index ix_order_lines_order_id on order_lines (order_id);")
                .startsWith("-- The schema of this project's entities").contains("for PostgreSQL.");

        // The same table as the other databases spell it.
        assertThat(SchemaSql.createTable(lines, SchemaDialect.ORACLE))
                .contains("id number(19,0) generated by default as identity not null")
                .contains("price number(19,2)").contains("deleted number(1,0) default 0 not null");
        assertThat(SchemaSql.createTable(lines, SchemaDialect.MSSQL))
                .contains("id bigint identity not null").contains("deleted bit default 0 not null");
        assertThat(SchemaSql.createTable(lines, SchemaDialect.DB2))
                .contains("id bigint generated by default as identity not null").contains("price decimal(19,2)");
    }

    @Test
    void aUniqueColumnThatMayBeNullIsAnIndexWhereAConstraintWouldNotDo() {
        Table people = table("people", List.of(ID, Column.varchar("email", 120, true)), List.of(),
                List.of(new Unique("uk_people_email", List.of("email"))), List.of());
        // PostgreSQL, Oracle and H2 compare no two nulls: a plain constraint.
        for (SchemaDialect dialect : List.of(SchemaDialect.POSTGRESQL, SchemaDialect.ORACLE, SchemaDialect.H2)) {
            assertThat(SchemaSql.baseline(schema(people), dialect)).as(dialect.name())
                    .contains("constraint uk_people_email unique (email)").doesNotContain("create unique");
        }
        // DB2 refuses a unique constraint over a nullable column; SQL Server would let one row be null.
        assertThat(SchemaSql.baseline(schema(people), SchemaDialect.DB2))
                .doesNotContain("constraint uk_people_email")
                .contains("create unique index uk_people_email on people (email) exclude null keys;");
        assertThat(SchemaSql.baseline(schema(people), SchemaDialect.MSSQL))
                .doesNotContain("constraint uk_people_email")
                .contains("create unique nonclustered index uk_people_email on people (email) where email is not null;");
        // Required, it is a constraint everywhere.
        assertThat(SchemaSql.baseline(schema(orders()), SchemaDialect.DB2)).contains("constraint uk_orders_code unique (code)");
    }

    @Test
    void aSchemaInItsOwnNamespaceIsCreatedWhereThatCanBeWritten() {
        Table table = new Table("sales", "orders", List.of(ID), List.of("id"), List.of(), List.of(), List.of());
        assertThat(SchemaSql.baseline(schema(table), SchemaDialect.POSTGRESQL))
                .contains("create schema if not exists sales;").contains("create table sales.orders (");
        assertThat(SchemaSql.baseline(schema(table), SchemaDialect.ORACLE))
                .doesNotContain("create schema").contains("-- The schema sales must exist before this runs.");
    }

    @Test
    void theSameSchemaNeedsNoMigration() {
        assertThat(SchemaDiff.between(schema(orders()), schema(orders()), SchemaDialect.H2).isEmpty()).isTrue();
        assertThat(SchemaDiff.migration(schema(orders()), schema(orders()), SchemaDialect.H2, "2026-11-15")).isNull();
    }

    @Test
    void whatTheModelAddsRunsAsItIs() {
        Table customers = table("customers", List.of(ID, Column.varchar("name", 255, false)), List.of(), List.of(), List.of());
        Table changed = table("orders",
                List.of(ID, Column.varchar("code", 40, false), Column.varchar("note", 255, true),
                        Column.of("customer_id", ColumnType.BIGINT, true),
                        new Column("deleted", ColumnType.BOOLEAN, null, false, false, true)),
                List.of(new ForeignKey("fk_orders_customer_id", List.of("customer_id"), null, "customers", List.of("id"))),
                List.of(new Unique("uk_orders_code", List.of("code"))),
                List.of(new Index("ix_orders_customer_id", List.of("customer_id"))));

        SchemaDiff.Result diff = SchemaDiff.between(schema(orders()), schema(changed, customers), SchemaDialect.POSTGRESQL);

        assertThat(diff.review()).isEmpty();
        assertThat(diff.live()).containsExactly(
                """
                create table customers (
                    id bigint generated by default as identity not null,
                    name varchar(255) not null,
                    constraint pk_customers primary key (id)
                );""",
                "alter table orders add column note varchar(255);",
                "alter table orders add column customer_id bigint;",
                // A flag the generator always writes has a default, so it can be added to a table with rows.
                "alter table orders add column deleted boolean default false not null;",
                // The foreign key and its index are on a column this migration adds: nothing to fail on.
                "alter table orders add constraint fk_orders_customer_id foreign key (customer_id) references customers (id);",
                "create index ix_orders_customer_id on orders (customer_id);");

        // Oracle and SQL Server say ADD, not ADD COLUMN.
        assertThat(SchemaDiff.between(schema(orders()), schema(changed, customers), SchemaDialect.ORACLE).live())
                .contains("alter table orders add note varchar2(255 char);");
        assertThat(SchemaDiff.between(schema(orders()), schema(changed, customers), SchemaDialect.MSSQL).live())
                .contains("alter table orders add deleted bit default 0 not null;");
    }

    @Test
    void aRequiredColumnIsAddedWithoutNotNullAndTheNotNullIsLeftForReview() {
        SchemaDiff.Result diff = SchemaDiff.between(schema(orders()),
                schema(orders(Column.varchar("owner", 80, false))), SchemaDialect.POSTGRESQL);

        assertThat(diff.live()).containsExactly("alter table orders add column owner varchar(80);");
        assertThat(diff.review()).hasSize(1);
        assertThat(diff.review().get(0))
                .startsWith("-- orders.owner is required by the model.")
                .endsWith("-- alter table orders alter column owner set not null;");
        assertThat(unwrapped(diff.review().get(0))).contains("since the table may have rows");
        // Every line of a review block is a comment: nothing in it runs.
        assertThat(diff.review().get(0).lines()).allMatch(line -> line.startsWith("--"));

        assertThat(SchemaDiff.between(schema(orders()), schema(orders(Column.varchar("owner", 80, false))),
                SchemaDialect.ORACLE).review().get(0)).endsWith("-- alter table orders modify owner not null;");
        assertThat(SchemaDiff.between(schema(orders()), schema(orders(Column.varchar("owner", 80, false))),
                SchemaDialect.MSSQL).review().get(0)).endsWith("-- alter table orders alter column owner varchar(80) not null;");
    }

    @Test
    void whatLosesDataOrCanFailIsCommentedOut() {
        Table before = table("orders",
                List.of(ID, Column.varchar("code", 40, false), Column.varchar("legacy", 20, true),
                        Column.of("amount", ColumnType.INTEGER, true), Column.varchar("status", 255, true),
                        Column.of("customer_id", ColumnType.BIGINT, true)),
                List.of(new ForeignKey("fk_orders_customer_id", List.of("customer_id"), null, "customers", List.of("id"))),
                List.of(), List.of(new Index("ix_orders_customer_id", List.of("customer_id"))));
        Table customers = table("customers", List.of(ID), List.of(), List.of(), List.of());
        Table after = table("orders",
                List.of(ID, Column.varchar("code", 40, false), Column.of("amount", ColumnType.MONEY, true),
                        Column.varchar("status", 255, false)),
                List.of(), List.of(new Unique("uk_orders_code", List.of("code"))), List.of());

        SchemaDiff.Result diff = SchemaDiff.between(schema(before, customers), schema(after), SchemaDialect.POSTGRESQL);

        assertThat(diff.live()).isEmpty();
        String review = String.join("\n\n", diff.review());
        assertThat(review.lines()).allMatch(line -> line.isEmpty() || line.startsWith("--"));
        assertThat(review)
                // A type change.
                .contains("-- alter table orders alter column amount type numeric(19,2);")
                // A column that became required.
                .contains("-- alter table orders alter column status set not null;")
                // A removed column — which may be a rename — and what hangs on it, first.
                .contains("-- alter table orders drop column legacy;")
                .contains("-- alter table orders drop constraint fk_orders_customer_id;\n"
                        + "-- drop index ix_orders_customer_id;\n"
                        + "-- alter table orders drop column customer_id;")
                // A unique constraint over values that are already there.
                .contains("-- alter table orders add constraint uk_orders_code unique (code);")
                // A removed table.
                .contains("-- drop table customers;");
        // Each under a line that says what changed and why it is not run.
        assertThat(unwrapped(review))
                .contains("orders.amount changed from integer to numeric(19,2). Values that do not fit the new type make this fail")
                .contains("orders.status is now required. Rows without a value make this fail")
                .contains("orders.legacy is no longer in the model; dropping it loses its values")
                .contains("If the field was renamed rather than removed, rename the column instead")
                .contains("code of orders must now be unique. Rows that share a value make this fail")
                .contains("customers is no longer in the model; dropping the table loses its rows.");
    }

    @Test
    void whatTheModelRelaxesRunsAsItIs() {
        Table before = table("orders", List.of(ID, Column.varchar("code", 40, false), Column.of("due", ColumnType.DATE, true)),
                List.of(), List.of(new Unique("uk_orders_code", List.of("code"))), List.of(new Index("ix_orders_due", List.of("due"))));
        Table after = table("orders", List.of(ID, Column.varchar("code", 40, true), Column.of("due", ColumnType.DATE, true)),
                List.of(), List.of(), List.of());

        assertThat(SchemaDiff.between(schema(before), schema(after), SchemaDialect.POSTGRESQL).live()).containsExactly(
                "alter table orders alter column code drop not null;",
                "alter table orders drop constraint uk_orders_code;",
                "drop index ix_orders_due;");
        assertThat(SchemaDiff.between(schema(before), schema(after), SchemaDialect.MSSQL).live()).containsExactly(
                "alter table orders alter column code varchar(40) null;",
                "alter table orders drop constraint uk_orders_code;",
                "drop index ix_orders_due on orders;");
        assertThat(SchemaDiff.between(schema(before), schema(after), SchemaDialect.ORACLE).live())
                .contains("alter table orders modify code null;");
    }

    @Test
    void aMigrationSaysWhatRunsAndWhatIsLeftToReview() {
        String migration = SchemaDiff.migration(schema(orders(Column.varchar("legacy", 20, true))),
                schema(orders(Column.varchar("note", 255, true))), SchemaDialect.DB2, "2026-11-15");

        assertThat(migration)
                .startsWith("-- What the changed model needs of the database, generated by the Menora Initializr on 2026-11-15 for DB2.")
                .contains("not of your database, which it has not seen")
                .contains("What the model adds runs as it is. What it removes or tightens is at the end, commented out")
                .contains("\nalter table orders add column note varchar(255);\n")
                .contains("-- ── To review ")
                .contains("-- alter table orders drop column legacy;");
        assertThat(unwrapped(migration)).contains("(DB2: run REORG TABLE on it afterwards)");
        // The live statement comes before the review section.
        assertThat(migration.indexOf("alter table orders add column note")).isLessThan(migration.indexOf("To review"));

        // Only removals: the header says nothing runs.
        assertThat(SchemaDiff.migration(schema(orders(Column.varchar("legacy", 20, true))), schema(orders()),
                SchemaDialect.H2, "2026-11-15"))
                .contains("Nothing in it runs as it is");
    }

    @Test
    void namesAreCutToWhatEveryDatabaseTakes() {
        assertThat(SchemaBuilder.constraint("fk", "order_lines", "order_id")).isEqualTo("fk_order_lines_order_id");
        // Exact-case names lose their quotes and anything that is not a letter, digit or underscore.
        assertThat(SchemaBuilder.constraint("ix", "\"Order Lines\"", "\"Order-Id\"")).isEqualTo("ix_order_lines_order_id");
        String longName = SchemaBuilder.constraint("fk", "a_table_with_a_very_long_name_indeed_it_is", "and_a_column_just_as_long_as_that");
        assertThat(longName).hasSizeLessThanOrEqualTo(60);
        assertThat(longName).isNotEqualTo(SchemaBuilder.constraint("fk", "a_table_with_a_very_long_name_indeed_it_is", "and_a_column_just_as_long_as_this"));
        assertThat(SchemaBuilder.name("\"Order\"")).isEqualTo("\"Order\"");
        assertThat(SchemaBuilder.name("`Order`")).isEqualTo("\"Order\"");
        assertThat(SchemaBuilder.name("[Order]")).isEqualTo("\"Order\"");
        assertThat(SchemaBuilder.name("orders")).isEqualTo("orders");
    }
}

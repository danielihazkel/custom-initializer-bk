/**
 * The live schema endpoints over HTTP against an in-memory H2 database that a test may read
 * ({@code menora.live-schema.allow-h2}): schemas, tables, the SQL wizard's script — generated
 * into a project — the fullstack import, the errors, and the admin's sources.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT, properties = {
        "menora.live-schema.allow-h2=true",
        "menora.live-schema.secrets.test-db=from-the-environment"})
@Import(TestInvokerConfiguration.class)
class LiveSchemaIntegrationTests {

    private static Connection keepAlive;

    @Autowired private TestRestTemplate rest;
    @Autowired private ObjectMapper json;
    @Autowired private SchemaSourceRepository sources;
    @Autowired private CatalogChangeRepository changes;

    @BeforeAll
    static void createDatabase() throws Exception {
        keepAlive = DriverManager.getConnection("jdbc:h2:mem:livetest;DB_CLOSE_DELAY=-1", "sa", "");
        try (Statement s = keepAlive.createStatement()) {
            s.execute("CREATE SCHEMA HR");
            s.execute("CREATE TABLE HR.DEPARTMENTS (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "NAME VARCHAR(100) NOT NULL UNIQUE, STATUS VARCHAR(10) CHECK (STATUS IN ('OPEN', 'CLOSED')), "
                    + "BUDGET NUMERIC(12,2))");
            s.execute("CREATE TABLE HR.EMPLOYEES (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "DEPT_ID BIGINT NOT NULL REFERENCES HR.DEPARTMENTS(ID), EMAIL VARCHAR(200) NOT NULL, "
                    + "HIRED DATE, CONSTRAINT UQ_EMP UNIQUE (EMAIL, DEPT_ID))");
            s.execute("CREATE VIEW HR.ACTIVE_STAFF AS SELECT ID, EMAIL, HIRED FROM HR.EMPLOYEES");
        }
    }

    @AfterAll
    static void dropDatabase() throws Exception {
        keepAlive.close();
    }

    @AfterEach
    void removeSources() {
        sources.deleteAll();
    }

    private static Map<String, Object> typed(String database) {
        Map<String, Object> c = new LinkedHashMap<>();
        c.put("dialect", "H2");
        c.put("host", "localhost");
        c.put("database", database);
        c.put("user", "sa");
        c.put("password", "");
        return c;
    }

    private static Map<String, Object> body(Map<String, Object> connection, String schema, List<String> tables) {
        Map<String, Object> b = new LinkedHashMap<>();
        b.put("connection", connection);
        if (schema != null) b.put("schema", schema);
        if (tables != null) b.put("tables", tables);
        return b;
    }

    private ResponseEntity<String> post(String url, Object body, HttpHeaders headers) {
        HttpHeaders h = headers != null ? headers : new HttpHeaders();
        h.setContentType(MediaType.APPLICATION_JSON);
        return rest.exchange(url, HttpMethod.POST, new HttpEntity<>(body, h), String.class);
    }

    private JsonNode ok(ResponseEntity<String> r) throws Exception {
        assertThat(r.getStatusCode()).as(r.getBody()).isEqualTo(HttpStatus.OK);
        return json.readTree(r.getBody());
    }

    @Test
    void offersTheDialectsWithADriver() throws Exception {
        JsonNode o = json.readTree(rest.getForObject("/metadata/live-schema/options", String.class));
        assertThat(o.path("typedConnections").asBoolean()).isTrue();
        assertThat(o.path("drivers").path("POSTGRESQL").asBoolean()).isTrue();
        assertThat(o.path("drivers").path("MSSQL").asBoolean()).isTrue();
        assertThat(o.path("drivers").path("ORACLE").asBoolean()).isTrue();
        assertThat(o.path("drivers").path("H2").asBoolean()).isTrue();
        assertThat(o.path("drivers").has("DB2")).isTrue();
        assertThat(o.path("defaultPorts").path("POSTGRESQL").asInt()).isEqualTo(5432);
    }

    @Test
    void listsSchemasAndTables() throws Exception {
        JsonNode schemas = ok(post("/metadata/live-schema/schemas", body(typed("livetest"), null, null), null));
        List<String> names = new ArrayList<>();
        schemas.path("schemas").forEach(n -> names.add(n.asText()));
        assertThat(names).contains("HR", "PUBLIC").doesNotContain("INFORMATION_SCHEMA");
        assertThat(schemas.path("defaultSchema").asText()).isEqualTo("PUBLIC");

        JsonNode tables = ok(post("/metadata/live-schema/tables", body(typed("livetest"), "HR", null), null));
        assertThat(tables.path("tables").toString())
                .contains("{\"name\":\"ACTIVE_STAFF\",\"kind\":\"VIEW\"}")
                .contains("{\"name\":\"DEPARTMENTS\",\"kind\":\"TABLE\"}")
                .contains("{\"name\":\"EMPLOYEES\",\"kind\":\"TABLE\"}");
    }

    @Test
    void writesTheScriptAndTheWizardGeneratesFromIt() throws Exception {
        JsonNode ddl = ok(post("/metadata/live-schema/ddl",
                body(typed("livetest"), "HR", List.of("departments", "EMPLOYEES", "ACTIVE_STAFF")), null));
        String sql = ddl.path("sql").asText();
        assertThat(ddl.path("dialect").asText()).isEqualTo("H2");
        assertThat(ddl.path("tables").asInt()).isEqualTo(2);
        assertThat(ddl.path("views").asInt()).isEqualTo(1);
        assertThat(sql).contains("-- Read from localhost/livetest, schema HR: 2 tables, 1 view.")
                .contains("CREATE TABLE HR.DEPARTMENTS (")
                .contains("ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL")
                .contains("NAME VARCHAR(100) NOT NULL")
                .contains("BUDGET NUMERIC(12,2)")
                .contains("UNIQUE (NAME)")
                .contains("CHECK (STATUS IN ('OPEN', 'CLOSED'))")
                .contains("UNIQUE (EMAIL, DEPT_ID)")
                .contains("ALTER TABLE HR.EMPLOYEES ADD FOREIGN KEY (DEPT_ID) REFERENCES HR.DEPARTMENTS (ID);")
                .contains("SELECT ID, EMAIL, HIRED FROM HR.ACTIVE_STAFF;")
                .doesNotContain("sa");

        Map<String, Object> wizard = new LinkedHashMap<>();
        wizard.put("groupId", "com.menora");
        wizard.put("artifactId", "demo");
        wizard.put("packageName", "com.menora.demo");
        wizard.put("dependencies", List.of("h2", "data-jpa"));
        wizard.put("sqlByDep", Map.of("h2", sql));
        HttpHeaders h = new HttpHeaders();
        h.setContentType(MediaType.APPLICATION_JSON);
        ResponseEntity<byte[]> zip = rest.exchange("/starter-wizard.zip", HttpMethod.POST, new HttpEntity<>(wizard, h), byte[].class);
        assertThat(zip.getStatusCode()).isEqualTo(HttpStatus.OK);
        Map<String, String> files = unzip(zip.getBody());
        String employees = files.entrySet().stream().filter(e -> e.getKey().endsWith("/entity/Employees.java"))
                .map(Map.Entry::getValue).findFirst().orElseThrow();
        assertThat(employees).contains("@ManyToOne").contains("@Table(name = \"EMPLOYEES\", schema = \"HR\"");
        assertThat(files.keySet()).anyMatch(p -> p.endsWith("/entity/ActiveStaff.java"))
                .anyMatch(p -> p.endsWith("/entity/DepartmentsStatus.java"));
    }

    @Test
    void importsEntitiesForTheFullstackEditor() throws Exception {
        JsonNode r = ok(post("/metadata/fullstack/import-live",
                body(typed("livetest"), "HR", List.of("DEPARTMENTS", "EMPLOYEES", "ACTIVE_STAFF")), null));
        JsonNode entities = r.path("entities");
        assertThat(entities).hasSize(3);
        JsonNode dept = find(entities, "Department");
        assertThat(field(dept, "status").path("type").asText()).isEqualTo("ENUM");
        assertThat(field(dept, "id").path("generated").asBoolean()).isTrue();
        JsonNode emp = find(entities, "Employee");
        assertThat(emp.path("relations").get(0).path("targetEntity").asText()).isEqualTo("Department");
        assertThat(emp.path("schema").asText()).isEqualTo("HR");
        JsonNode view = find(entities, "ActiveStaff");
        assertThat(view.path("readOnly").asBoolean()).isTrue();
        assertThat(view.path("viewQuery").asText()).isEqualTo("SELECT ID, EMAIL, HIRED FROM HR.ACTIVE_STAFF");
        assertThat(field(view, "ID").path("type").asText()).isEqualTo("LONG");
        assertThat(field(view, "ID").path("primaryKey").asBoolean()).isTrue();
        assertThat(field(view, "EMAIL").path("length").asInt()).isEqualTo(200);
        assertThat(field(view, "EMAIL").path("type").asText()).isEqualTo("STRING");
        assertThat(field(view, "HIRED").path("type").asText()).isEqualTo("LOCAL_DATE");
        assertThat(r.path("note").asText()).contains("first column was made the key");
    }

    @Test
    void saysWhatIsWrong() throws Exception {
        ResponseEntity<String> unknownTable = post("/metadata/live-schema/ddl",
                body(typed("livetest"), "HR", List.of("NOPE")), null);
        assertThat(unknownTable.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(unknownTable.getBody()).contains("Schema HR has no table or view NOPE");

        ResponseEntity<String> noDatabase = post("/metadata/live-schema/schemas", body(typed("nosuchdb"), null, null), null);
        assertThat(noDatabase.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(noDatabase.getBody()).contains("Could not connect");

        Map<String, Object> injected = typed("livetest;INIT=RUNSCRIPT FROM 'x'");
        ResponseEntity<String> injection = post("/metadata/live-schema/schemas", body(injected, null, null), null);
        assertThat(injection.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(injection.getBody()).contains("Database: letters, digits");

        Map<String, Object> mysql = typed("livetest");
        mysql.put("dialect", "MYSQL");
        assertThat(post("/metadata/live-schema/schemas", body(mysql, null, null), null).getBody())
                .contains("Database type must be one of");

        ResponseEntity<String> noTables = post("/metadata/live-schema/ddl", body(typed("livetest"), "HR", List.of()), null);
        assertThat(noTables.getBody()).contains("Pick at least one table or view");

        Map<String, Object> unknownSource = Map.of("source", "nope");
        assertThat(post("/metadata/live-schema/schemas", body(unknownSource, null, null), null).getStatusCode())
                .isEqualTo(HttpStatus.NOT_FOUND);
    }

    @Test
    void adminSourcesKeepTheirPasswordOutOfTheDatabase() throws Exception {
        HttpHeaders admin = adminHeaders();
        Map<String, Object> source = new LinkedHashMap<>();
        source.put("name", "HR reporting");
        source.put("dialect", "POSTGRESQL");
        source.put("host", "127.0.0.1");
        source.put("port", 1);
        source.put("databaseName", "hr");
        source.put("username", "reader");
        source.put("passwordRef", "menora.live-schema.secrets.test-db");
        source.put("defaultSchema", "public");
        JsonNode saved = ok(post("/admin/schema-sources", source, admin));
        assertThat(saved.path("passwordAvailable").asBoolean()).isTrue();
        assertThat(saved.toString()).doesNotContain("from-the-environment");

        // Everyone sees its name, not where it is.
        JsonNode options = json.readTree(rest.getForObject("/metadata/live-schema/options", String.class));
        assertThat(options.path("sources").toString()).contains("\"name\":\"HR reporting\"").doesNotContain("127.0.0.1");

        // Reading through it connects with the stored parts (nothing listens on port 1).
        ResponseEntity<String> read = post("/metadata/live-schema/schemas", body(Map.of("source", "hr reporting"), null, null), null);
        assertThat(read.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(read.getBody()).contains("Could not connect to HR reporting").doesNotContain("from-the-environment");

        JsonNode test = ok(post("/admin/schema-sources/test", source, admin));
        assertThat(test.path("ok").asBoolean()).isFalse();
        assertThat(test.path("message").asText()).contains("Could not connect");

        source.put("name", "HR REPORTING");
        assertThat(post("/admin/schema-sources", source, admin).getStatusCode()).isEqualTo(HttpStatus.CONFLICT);

        source.put("name", "Other");
        source.put("passwordRef", "admin.password");
        ResponseEntity<String> badRef = post("/admin/schema-sources", source, admin);
        assertThat(badRef.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);
        assertThat(badRef.getBody()).contains("SCHEMA_SOURCE_");

        source.put("passwordRef", "SCHEMA_SOURCE_NOT_SET");
        JsonNode unset = ok(post("/admin/schema-sources", source, admin));
        assertThat(unset.path("passwordAvailable").asBoolean()).isFalse();
        assertThat(ok(post("/admin/schema-sources/test", source, admin)).path("message").asText())
                .contains("is not set on this server (SCHEMA_SOURCE_NOT_SET)");

        source.put("databaseName", "hr;socketFactory=x");
        assertThat(post("/admin/schema-sources", source, admin).getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST);

        // Like every catalog row, a source's changes are in the history.
        assertThat(changes.findAll()).anyMatch(c -> c.getEntityType().equals("SchemaSourceEntity")
                && "HR reporting".equals(c.getLabel()));

        assertThat(rest.getForEntity("/admin/schema-sources", String.class).getStatusCode())
                .isEqualTo(HttpStatus.UNAUTHORIZED);
    }

    private HttpHeaders adminHeaders() throws Exception {
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        ResponseEntity<String> login = rest.exchange("/admin/login", HttpMethod.POST,
                new HttpEntity<>(Map.of("password", "test"), headers), String.class);
        headers.setBearerAuth(json.readTree(login.getBody()).get("token").asText());
        return headers;
    }

    private static JsonNode find(JsonNode entities, String name) {
        for (JsonNode e : entities) if (e.path("name").asText().equals(name)) return e;
        throw new AssertionError("No entity " + name + " in " + entities);
    }

    private static JsonNode field(JsonNode entity, String name) {
        for (JsonNode f : entity.path("fields")) if (f.path("name").asText().equals(name)) return f;
        throw new AssertionError("No field " + name + " in " + entity);
    }

    private static Map<String, String> unzip(byte[] zip) throws Exception {
        Map<String, String> out = new LinkedHashMap<>();
        try (ZipInputStream zis = new ZipInputStream(new ByteArrayInputStream(zip))) {
            ZipEntry entry;
            while ((entry = zis.getNextEntry()) != null) {
                if (!entry.isDirectory()) out.put(entry.getName(), new String(zis.readAllBytes(), StandardCharsets.UTF_8));
            }
        }
        return out;
    }
}

    @ParameterizedTest
    @EnumSource(Db.class)
    void readsARealServer(Db db) throws Exception {
        int hostPort;
        try (ServerSocket s = new ServerSocket(0)) {
            hostPort = s.getLocalPort();
        }
        List<String> run = new ArrayList<>(List.of("docker", "run", "-d", "--rm", "-p", hostPort + ":" + db.port));
        run.addAll(db.env);
        run.add(db.image);
        String container = exec(run, Duration.ofMinutes(10)).trim();
        try {
            SqlDialect dialect = SqlDialect.valueOf(db.name());
            ConnectionSpec spec = new ConnectionSpec(dialect, "127.0.0.1", hostPort, db.database, null, db.user,
                    db.password, true, "docker").validated();
            LiveSchemaReader reader = new LiveSchemaReader(DialectSupport.of(dialect));
            try (Connection c = waitFor(reader, spec)) {
                c.setReadOnly(false);
                try (Statement st = c.createStatement()) {
                    for (String sql : db.setup) st.execute(sql);
                }
            }
            String ddl;
            try (Connection c = reader.connect(spec)) {
                LiveSchemaReader.Schemas schemas = reader.schemas(c);
                String schema = schemas.schemas().stream().filter(s -> s.equalsIgnoreCase(db.schema)).findFirst().orElseThrow();
                List<String> names = reader.tables(c, schema).tables().stream().map(LiveSchemaModel.TableRef::name).toList();
                assertThat(names).hasSize(3);
                LiveSchemaModel.Schema read = reader.read(c, schema, names);
                assertThat(read.warnings()).isEmpty();
                // Every catalog query ran: none was answered by the driver instead.
                assertThat(reader.refusedQueries()).isEmpty();
                ddl = LiveDdlWriter.write(reader.support(), read, "docker", true);
                for (String line : db.script) assertThat(ddl).contains(line);

                // And the driver, asked table by table, says the same of keys and unique constraints.
                LiveSchemaModel.Schema byDriver = new LiveSchemaReader(DialectSupport.of(dialect), false).read(c, schema, names);
                for (LiveSchemaModel.Table table : read.tables()) {
                    LiveSchemaModel.Table other = byDriver.tables().stream()
                            .filter(t -> t.name().equals(table.name())).findFirst().orElseThrow();
                    assertThat(other.primaryKey()).as(table.name()).isEqualTo(table.primaryKey());
                    assertThat(other.foreignKeys()).as(table.name()).containsExactlyInAnyOrderElementsOf(table.foreignKeys());
                    assertThat(other.uniqueKeys().stream().map(java.util.TreeSet::new).toList()).as(table.name())
                            .containsExactlyInAnyOrderElementsOf(table.uniqueKeys().stream().map(java.util.TreeSet::new).toList());
                    assertThat(other.indexes().stream().filter(i -> i.skipped() == null).map(LiveSchemaModel.Index::name).toList())
                            .as(table.name()).containsAll(table.indexes().stream().filter(i -> i.skipped() == null)
                                    .map(LiveSchemaModel.Index::name).toList());
                }
            }
            SqlEntityGenerator generator = new SqlEntityGenerator();
            List<EntityDefinition> entities = new SqlToEntityDefinitionConverter(generator).convert(ddl, dialect);
            EntityDefinition dept = entities.stream().filter(e -> e.name().equals("Department")).findFirst().orElseThrow();
            assertThat(dept.fields().get(0).generated()).as(ddl).isTrue();
            assertThat(dept.fields().stream().filter(f -> f.type() == FieldType.ENUM)).as(ddl).hasSize(1);
            assertThat(entities.stream().filter(e -> e.name().equals("Employee")).findFirst().orElseThrow().relations())
                    .as(ddl).hasSize(1);
            assertThat(generator.parseTablesForImport(ddl, dialect).stream().filter(t -> t.isView())).hasSize(1);
            // The wizard reads the index, and types the view's fields by their casts.
            List<com.menora.initializr.sql.GeneratedJavaFile> files = generator.generate(ddl, dialect, "com.menora.demo",
                    new com.menora.initializr.sql.SqlDepOptions("entity", List.of()));
            assertThat(files.stream().filter(f -> f.relativePath().endsWith("/Employees.java")).findFirst().orElseThrow().content())
                    .as(ddl).contains("@Index(name = ");
            assertThat(files.stream().filter(f -> f.relativePath().endsWith("/ActiveStaff.java")).findFirst().orElseThrow().content())
                    .as(ddl).contains("private Long id;").contains("private String email;").doesNotContain("TODO");

            if (db == Db.POSTGRESQL) {
                // The script is a baseline: it creates the same tables in an empty schema.
                String unqualified;
                try (Connection c = reader.connect(spec)) {
                    LiveSchemaModel.Schema read = reader.read(c, "hr", List.of("departments", "employees"));
                    unqualified = LiveDdlWriter.write(reader.support(), read, "docker", false);
                }
                try (Connection c = reader.connect(spec); Statement st = c.createStatement()) {
                    c.setReadOnly(false);
                    st.execute("CREATE SCHEMA hr2");
                    st.execute("SET search_path TO hr2");
                    for (String sql : SqlStatements.of(unqualified)) st.execute(sql);
                }
            }
        } finally {
            exec(List.of("docker", "rm", "-f", container), Duration.ofMinutes(2));
        }
    }

    /** Statements of a script, comments left out — enough for the scripts the writer makes. */
    static final class SqlStatements {
        static List<String> of(String script) {
            List<String> out = new ArrayList<>();
            StringBuilder cur = new StringBuilder();
            for (String line : script.split("\n")) {
                if (line.startsWith("--")) continue;
                cur.append(line).append('\n');
                if (line.trim().endsWith(";")) {
                    String s = cur.toString().trim();
                    out.add(s.substring(0, s.length() - 1));
                    cur.setLength(0);
                }
            }
            return out;
        }
    }

    private static Connection waitFor(LiveSchemaReader reader, ConnectionSpec spec) throws Exception {
        Instant until = Instant.now().plus(Duration.ofMinutes(4));
        while (true) {
            try {
                return reader.connect(spec);
            } catch (LiveSchemaException e) {
                if (Instant.now().isAfter(until)) throw e;
                Thread.sleep(3000);
            }
        }
    }

    private static String exec(List<String> command, Duration timeout) throws Exception {
        Process p = new ProcessBuilder(command).redirectErrorStream(true).start();
        if (!p.waitFor(timeout.toSeconds(), TimeUnit.SECONDS)) {
            p.destroyForcibly();
            throw new AssertionError("Timed out: " + command);
        }
        String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        if (p.exitValue() != 0) throw new AssertionError(command + " failed: " + out);
        return out;
    }

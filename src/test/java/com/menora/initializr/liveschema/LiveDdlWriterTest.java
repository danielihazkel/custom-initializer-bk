    void urlsAreBuiltFromTheParts() {
        ConnectionSpec spec = new ConnectionSpec(SqlDialect.MSSQL, "sql01.menora.co.il", null, "Hr", null, "reader",
                "secret", true, "sql01/Hr");
        String url = DialectSupport.of(SqlDialect.MSSQL).url(spec);
        assertThat(url).startsWith("jdbc:sqlserver://sql01.menora.co.il:1433;databaseName=Hr;")
                .contains("trustServerCertificate=true").doesNotContain("secret");
        assertThat(DialectSupport.of(SqlDialect.ORACLE).url(new ConnectionSpec(SqlDialect.ORACLE, "ora", 1522, "HRPDB",
                null, "u", null, false, "x"))).isEqualTo("jdbc:oracle:thin:@//ora:1522/HRPDB");
        assertThat(DialectSupport.of(SqlDialect.DB2).url(new ConnectionSpec(SqlDialect.DB2, "as400", null, null,
                "HRLIB", "u", null, false, "x"))).isEqualTo("jdbc:as400://as400;libraries=HRLIB");
        assertThat(DialectSupport.of(SqlDialect.POSTGRESQL).properties(spec).getProperty("password")).isEqualTo("secret");
        assertThat(spec.toString()).doesNotContain("secret");
    }

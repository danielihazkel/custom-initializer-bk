    private void assertViewFields(SqlDialect dialect, List<Column> columns, String select, String... fields) {
        DialectSupport support = DialectSupport.of(dialect);
        String schema = support.fold("s");
        Table view = new Table(schema, support.fold("v"), Kind.VIEW, columns, List.of(), List.of(), List.of(), List.of());
        String typed = LiveDdlWriter.typedSelectOf(support, view, true);
        if (select != null) assertThat(typed).isEqualTo(select);
        String entity = generator.generate(typed + ";", dialect, "p", new SqlDepOptions("entity", List.of())).get(0).content();
        for (String field : fields) assertThat(entity).as(dialect + ": " + typed).contains("    private " + field + ";");
        long todos = entity.split("TODO: SELECT has no column types", -1).length - 1;
        // What no cast is written for is still to be typed by hand: here, the array and the bytes.
        assertThat(todos).as(entity).isEqualTo(java.util.Arrays.stream(fields)
                .filter(f -> f.equals("String blob") || f.equals("String tags")).count());
    }


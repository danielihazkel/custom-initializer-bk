    /** The script parses into both tables and the view, and imports as two related entities. */
    private void assertEntities(String ddl, SqlDialect dialect, String fkColumn) {
        List<TableModel> tables = generator.parseTablesForImport(ddl, dialect);
        assertThat(tables).hasSize(3);
        TableModel dept = tables.get(0);
        assertThat(dept.pkColumns()).hasSize(1);
        ColumnModel id = dept.columns().get(0);
        assertThat(id.isAutoIncrement()).isTrue();
        assertThat(dept.columns().get(1).isUnique()).isTrue();
        assertThat(dept.enumValues()).isNotEmpty();
        TableModel emp = tables.get(1);
        assertThat(emp.foreignKeys()).hasSize(1);
        assertThat(emp.uniqueConstraints()).hasSize(1);
        assertThat(tables.get(2).isView()).isTrue();

        List<EntityDefinition> entities = converter.convert(ddl, dialect);
        EntityDefinition department = entities.stream().filter(e -> e.name().equals("Department")).findFirst().orElseThrow();
        assertThat(field(department, 0).type()).isEqualTo(FieldType.LONG);
        assertThat(field(department, 0).generated()).isTrue();
        assertThat(field(department, 1).type()).isEqualTo(FieldType.STRING);
        assertThat(field(department, 1).length()).isEqualTo(100);
        assertThat(field(department, 1).required()).isTrue();
        assertThat(field(department, 2).type()).isEqualTo(FieldType.ENUM);
        assertThat(field(department, 2).enumValues()).containsExactly("OPEN", "CLOSED");
        assertThat(field(department, 3).type()).isEqualTo(FieldType.BIG_DECIMAL);
        assertThat(field(department, 4).type()).isIn(FieldType.INSTANT, FieldType.LOCAL_DATE_TIME);
        EntityDefinition employee = entities.stream().filter(e -> e.name().equals("Employee")).findFirst().orElseThrow();
        assertThat(employee.relations()).singleElement().satisfies(r -> {
            assertThat(r.targetEntity()).isEqualTo("Department");
            assertThat(r.joinColumn().replaceAll("[\\[\\]\"]", "")).isEqualToIgnoringCase(fkColumn);
            assertThat(r.required()).isTrue();
        });

        // And the wizard writes the entities, the view among them.
        List<GeneratedJavaFile> files = generator.generate(ddl, dialect, "com.menora.demo", new SqlDepOptions("entity", List.of()));
        assertThat(files).extracting(GeneratedJavaFile::relativePath)
                .anyMatch(p -> p.endsWith("/Departments.java") || p.endsWith("/Department.java"))
                .anyMatch(p -> p.endsWith("/ActiveStaff.java"));
    }

    private static FieldDefinition field(EntityDefinition e, int i) {
        return e.fields().get(i);
    }

    @Test
    void indexesDefaultsAndCommentsAreWritten() {
        DialectSupport pg = DialectSupport.of(SqlDialect.POSTGRESQL);
        Table orders = new Table("public", "orders", Kind.TABLE, List.of(
                new Column("id", "bigserial", 19, 0, false, true, "nextval('orders_id_seq'::regclass)", null),
                new Column("status", "varchar", 10, 0, false, false, "'open'::character varying", "Where the order is"),
                new Column("total", "numeric", 12, 2, true, false, "0", null),
                new Column("placed_at", "timestamp", 29, 6, true, false, "now()", null),
                new Column("ref", "uuid", 2147483647, 0, true, false, "gen_random_uuid()", null)),
                List.of("id"), List.of(), List.of(), List.of(),
                List.of(new Index("idx_orders_placed", false, List.of(new IndexColumn("placed_at", true), new IndexColumn("status", false)), null),
                        new Index("idx_orders_open", false, List.of(new IndexColumn("status", false)), "it is partial"),
                        new Index("uq_orders_lower", true, List.of(), "it is over an expression"),
                        new Index("idx_orders_ref", false, List.of(new IndexColumn("ref", false)), "it is a hash index")),
                "Orders, one row each");
        Table view = new Table("public", "open_orders", Kind.VIEW, List.of(
                new Column("id", "int8", 19, 0, true, false, null, "The order's id")),
                List.of(), List.of(), List.of(), List.of(), List.of(), "Orders nobody closed");
        String ddl = LiveDdlWriter.write(pg, new LiveSchemaModel.Schema("public", List.of(orders, view), List.of()), "db", false);
        assertThat(ddl)
                // The identity says how the key is made; the sequence call behind it is not a default to copy.
                .contains("    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n")
                .contains("    status VARCHAR(10) DEFAULT 'open' NOT NULL,\n")
                .contains("    total NUMERIC(12,2) DEFAULT 0,\n")
                .contains("    placed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n")
                .contains("    ref UUID, -- default in the database: gen_random_uuid()\n")
                .contains("CREATE INDEX idx_orders_placed ON orders (placed_at DESC, status);")
                .contains("-- Index idx_orders_open on orders is not in this script: it is partial.")
                .contains("-- Unique index uq_orders_lower on orders is not in this script: it is over an expression.")
                .contains("-- Index idx_orders_ref on orders is not in this script: it is a hash index.")
                .contains("COMMENT ON TABLE orders IS 'Orders, one row each';")
                .contains("COMMENT ON COLUMN orders.status IS 'Where the order is';")
                // The script does not create the view, so what is said of it is a comment, not a statement.
                .contains("-- open_orders: Orders nobody closed")
                .contains("-- open_orders.id: The order's id")
                .doesNotContain("COMMENT ON TABLE open_orders");

        List<TableModel> tables = generator.parseTablesForImport(ddl, SqlDialect.POSTGRESQL);
        assertThat(tables).hasSize(2);
        assertThat(tables.get(0).indexes()).singleElement().satisfies(ix -> {
            assertThat(ix.name()).isEqualTo("idx_orders_placed");
            assertThat(ix.columns()).extracting(c -> c.name() + (c.descending() ? " DESC" : ""))
                    .containsExactly("placed_at DESC", "status");
        });

        // SQL Server has no COMMENT ON: a description is a comment of the script.
        DialectSupport ms = DialectSupport.of(SqlDialect.MSSQL);
        Table items = new Table("dbo", "Items", Kind.TABLE, List.of(
                new Column("Id", "int identity", 10, 0, false, true),
                new Column("Qty", "int", 10, 0, false, false, "((1))", "How many"),
                new Column("Label", "nvarchar", 50, 0, true, false, "(N'none')", null),
                new Column("Made", "datetime2", 27, 7, true, false, "(getdate())", null),
                new Column("Stamp", "datetime2", 27, 7, true, false, "(sysutcdatetime())", null)),
                List.of("Id"), List.of(), List.of(), List.of(), List.of(), "What is in stock");
        String tsql = LiveDdlWriter.write(ms, new LiveSchemaModel.Schema("dbo", List.of(items), List.of()), "db", true);
        assertThat(tsql)
                .contains("    Qty INT DEFAULT 1 NOT NULL,\n")
                .contains("    Label NVARCHAR(50) DEFAULT 'none',\n")
                .contains("    Made DATETIME2 DEFAULT CURRENT_TIMESTAMP,\n")
                .contains("    Stamp DATETIME2, -- default in the database: (sysutcdatetime())\n")
                .contains("-- dbo.Items: What is in stock")
                .contains("-- dbo.Items.Qty: How many")
                .doesNotContain("COMMENT ON");
        assertThat(generator.parseTablesForImport(tsql, SqlDialect.MSSQL)).hasSize(1);
    }

    @Test
    void aDefaultIsWrittenOnlyWhenTheScriptCanCarryIt() {
        assertThat(LiveDdlWriter.defaultLiteral("0")).isEqualTo("0");
        assertThat(LiveDdlWriter.defaultLiteral("-1.50")).isEqualTo("-1.50");
        assertThat(LiveDdlWriter.defaultLiteral("'it''s'")).isEqualTo("'it''s'");
        assertThat(LiveDdlWriter.defaultLiteral("'open'::character varying")).isEqualTo("'open'");
        assertThat(LiveDdlWriter.defaultLiteral("'2020-01-01'::date")).isEqualTo("'2020-01-01'");
        assertThat(LiveDdlWriter.defaultLiteral("0::numeric(10,2)")).isEqualTo("0");
        assertThat(LiveDdlWriter.defaultLiteral("((0))")).isEqualTo("0");
        assertThat(LiveDdlWriter.defaultLiteral("('a(b)')")).isEqualTo("'a(b)'");
        assertThat(LiveDdlWriter.defaultLiteral("(N'x')")).isEqualTo("'x'");
        assertThat(LiveDdlWriter.defaultLiteral("now()")).isEqualTo("CURRENT_TIMESTAMP");
        assertThat(LiveDdlWriter.defaultLiteral("(getdate())")).isEqualTo("CURRENT_TIMESTAMP");
        assertThat(LiveDdlWriter.defaultLiteral("CURRENT TIMESTAMP")).isEqualTo("CURRENT_TIMESTAMP");
        assertThat(LiveDdlWriter.defaultLiteral("sysdate ")).isEqualTo("SYSDATE");
        assertThat(LiveDdlWriter.defaultLiteral("true")).isEqualTo("TRUE");
        // A sequence, a function, an expression, a cast of something that is not a literal.
        assertThat(LiveDdlWriter.defaultLiteral("nextval('s'::regclass)")).isNull();
        assertThat(LiveDdlWriter.defaultLiteral("\"HR\".\"ISEQ$$_73\".nextval")).isNull();
        assertThat(LiveDdlWriter.defaultLiteral("gen_random_uuid()")).isNull();
        assertThat(LiveDdlWriter.defaultLiteral("(1)+(2)")).isNull();
        assertThat(LiveDdlWriter.defaultLiteral("(now() + '1 day'::interval)")).isNull();
        assertThat(LiveDdlWriter.defaultLiteral("NULL")).isNull();
    }


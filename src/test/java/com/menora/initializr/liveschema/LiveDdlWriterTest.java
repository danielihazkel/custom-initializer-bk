/**
 * What each driver reports, written as DDL and read back by the SQL wizard's own parser — the
 * check that a schema read from PostgreSQL, SQL Server, Oracle or DB2 for IBM i becomes the same
 * entities as its script pasted would. The column descriptions are those each driver documents
 * for {@code getColumns} ({@code TYPE_NAME}, {@code COLUMN_SIZE}, {@code DECIMAL_DIGITS}); the
 * Docker tests read real servers.
 */
class LiveDdlWriterTest {

    private final SqlEntityGenerator generator = new SqlEntityGenerator();
    private final SqlToEntityDefinitionConverter converter = new SqlToEntityDefinitionConverter(generator);

    /** departments + employees (a foreign key, a two-column unique) + a view, in the driver's words. */
    private static LiveSchemaModel.Schema schema(String schema, String departments, String employees, String view,
                                                 Column id, Column name, Column status, Column budget, Column created,
                                                 Column deptId, Column email, Column notes, String statusCol) {
        Table dept = new Table(schema, departments, Kind.TABLE, List.of(id, name, status, budget, created),
                List.of(id.name()), List.of(), List.of(List.of(name.name())),
                List.of(new CheckIn(statusCol, List.of("OPEN", "CLOSED"))));
        Column empId = new Column(id.name(), id.typeName(), id.size(), id.digits(), false, true);
        Table emp = new Table(schema, employees, Kind.TABLE, List.of(empId, deptId, email, notes),
                List.of(id.name()), List.of(new ForeignKey(List.of(deptId.name()), schema, departments, List.of(id.name()))),
                List.of(List.of(email.name(), deptId.name())), List.of());
        Table v = new Table(schema, view, Kind.VIEW, List.of(id, name), List.of(), List.of(), List.of(), List.of());
        return new LiveSchemaModel.Schema(schema, List.of(dept, emp, v), List.of());
    }

    @Test
    void postgres() {
        DialectSupport pg = DialectSupport.of(SqlDialect.POSTGRESQL);
        var read = schema("hr", "departments", "employees", "active_staff",
                new Column("id", "bigserial", 19, 0, false, true),
                new Column("name", "varchar", 100, 0, false, false),
                new Column("status", "varchar", 10, 0, true, false),
                new Column("budget", "numeric", 12, 2, true, false),
                new Column("created_at", "timestamptz", 35, 6, true, false),
                new Column("dept_id", "int8", 19, 0, false, false),
                new Column("email", "varchar", 200, 0, false, false),
                new Column("notes", "text", 2147483647, 0, true, false), "status");
        String ddl = LiveDdlWriter.write(pg, read, "db.example/hr", true);
        assertThat(ddl).contains("CREATE TABLE hr.departments (")
                .contains("id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL")
                .contains("budget NUMERIC(12,2)")
                .contains("created_at TIMESTAMPTZ")
                .contains("CHECK (status IN ('OPEN', 'CLOSED'))")
                .contains("ALTER TABLE hr.employees ADD FOREIGN KEY (dept_id) REFERENCES hr.departments (id);")
                .contains("SELECT id, name FROM hr.active_staff;");
        assertEntities(ddl, SqlDialect.POSTGRESQL, "dept_id");
    }

    @Test
    void sqlServer() {
        DialectSupport ms = DialectSupport.of(SqlDialect.MSSQL);
        var read = schema("dbo", "Departments", "Employees", "ActiveStaff",
                new Column("Id", "bigint identity", 19, 0, false, true),
                new Column("Name", "nvarchar", 100, 0, false, false),
                new Column("Status", "varchar", 10, 0, true, false),
                new Column("Budget", "decimal", 12, 2, true, false),
                new Column("CreatedAt", "datetimeoffset", 34, 7, true, false),
                new Column("DeptId", "bigint", 19, 0, false, false),
                new Column("Email", "nvarchar", 200, 0, false, false),
                new Column("Notes", "nvarchar", 1073741823, 0, true, false), "Status");
        String ddl = LiveDdlWriter.write(ms, read, "sql01/Hr", true);
        assertThat(ddl).contains("CREATE TABLE dbo.Departments (")
                .contains("Id BIGINT IDENTITY(1,1) NOT NULL")
                .contains("Notes NVARCHAR(MAX)")
                .contains("Budget DECIMAL(12,2)");
        assertEntities(ddl, SqlDialect.MSSQL, "DeptId");
    }

    @Test
    void oracle() {
        DialectSupport ora = DialectSupport.of(SqlDialect.ORACLE);
        var read = schema("HR", "DEPARTMENTS", "EMPLOYEES", "ACTIVE_STAFF",
                new Column("ID", "NUMBER", 18, 0, false, true),
                new Column("NAME", "VARCHAR2", 100, 0, false, false),
                new Column("STATUS", "VARCHAR2", 10, 0, true, false),
                new Column("BUDGET", "NUMBER", 12, 2, true, false),
                new Column("CREATED_AT", "TIMESTAMP(6) WITH TIME ZONE", 13, 6, true, false),
                new Column("DEPT_ID", "NUMBER", 18, 0, false, false),
                new Column("EMAIL", "VARCHAR2", 200, 0, false, false),
                new Column("NOTES", "CLOB", 4000, 0, true, false), "STATUS");
        String ddl = LiveDdlWriter.write(ora, read, "ora01/HRPDB", true);
        assertThat(ddl).contains("ID NUMBER(18) GENERATED BY DEFAULT AS IDENTITY NOT NULL")
                .contains("CREATED_AT TIMESTAMP WITH TIME ZONE")
                .contains("CHECK (STATUS IN ('OPEN', 'CLOSED'))");
        assertEntities(ddl, SqlDialect.ORACLE, "DEPT_ID");
    }

    @Test
    void db2ForI() {
        DialectSupport db2 = DialectSupport.of(SqlDialect.DB2);
        var read = schema("HRLIB", "DEPARTMENTS", "EMPLOYEES", "ACTIVE_STAFF",
                new Column("ID", "BIGINT", 19, 0, false, true),
                new Column("NAME", "VARCHAR", 100, 0, false, false),
                new Column("STATUS", "CHAR", 10, 0, true, false),
                new Column("BUDGET", "DECIMAL", 12, 2, true, false),
                new Column("CREATED_AT", "TIMESTAMP", 26, 6, true, false),
                new Column("DEPT_ID", "BIGINT", 19, 0, false, false),
                new Column("EMAIL", "VARCHAR", 200, 0, false, false),
                new Column("NOTES", "CLOB", 1048576, 0, true, false), "STATUS");
        String ddl = LiveDdlWriter.write(db2, read, "as400", true);
        assertThat(ddl).contains("ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL").contains("BUDGET DECIMAL(12,2)");
        assertEntities(ddl, SqlDialect.DB2, "DEPT_ID");
    }

    /** The script parses into both tables and the view, and imports as two related entities. */
    private void assertEntities(String ddl, SqlDialect dialect, String fkColumn) {
        List<TableModel> tables = generator.parseTablesForImport(ddl, dialect);
        assertThat(tables).hasSize(3);
        TableModel dept = tables.get(0);
        assertThat(dept.pkColumns()).hasSize(1);
        ColumnModel id = dept.columns().get(0);
        assertThat(id.isAutoIncrement()).isTrue();
        assertThat(dept.columns().get(1).isUnique()).isTrue();
        assertThat(dept.enumValues()).isNotEmpty();
        TableModel emp = tables.get(1);
        assertThat(emp.foreignKeys()).hasSize(1);
        assertThat(emp.uniqueConstraints()).hasSize(1);
        assertThat(tables.get(2).isView()).isTrue();

        List<EntityDefinition> entities = converter.convert(ddl, dialect);
        EntityDefinition department = entities.stream().filter(e -> e.name().equals("Department")).findFirst().orElseThrow();
        assertThat(field(department, 0).type()).isEqualTo(FieldType.LONG);
        assertThat(field(department, 0).generated()).isTrue();
        assertThat(field(department, 1).type()).isEqualTo(FieldType.STRING);
        assertThat(field(department, 1).length()).isEqualTo(100);
        assertThat(field(department, 1).required()).isTrue();
        assertThat(field(department, 2).type()).isEqualTo(FieldType.ENUM);
        assertThat(field(department, 2).enumValues()).containsExactly("OPEN", "CLOSED");
        assertThat(field(department, 3).type()).isEqualTo(FieldType.BIG_DECIMAL);
        assertThat(field(department, 4).type()).isIn(FieldType.INSTANT, FieldType.LOCAL_DATE_TIME);
        EntityDefinition employee = entities.stream().filter(e -> e.name().equals("Employee")).findFirst().orElseThrow();
        assertThat(employee.relations()).singleElement().satisfies(r -> {
            assertThat(r.targetEntity()).isEqualTo("Department");
            assertThat(r.joinColumn().replaceAll("[\\[\\]\"]", "")).isEqualToIgnoringCase(fkColumn);
            assertThat(r.required()).isTrue();
        });

        // And the wizard writes the entities, the view among them.
        List<GeneratedJavaFile> files = generator.generate(ddl, dialect, "com.menora.demo", new SqlDepOptions("entity", List.of()));
        assertThat(files).extracting(GeneratedJavaFile::relativePath)
                .anyMatch(p -> p.endsWith("/Departments.java") || p.endsWith("/Department.java"))
                .anyMatch(p -> p.endsWith("/ActiveStaff.java"));
    }

    private static FieldDefinition field(EntityDefinition e, int i) {
        return e.fields().get(i);
    }

    @Test
    void namesThatAreNotPlainAreQuoted() {
        DialectSupport pg = DialectSupport.of(SqlDialect.POSTGRESQL);
        assertThat(LiveDdlWriter.ident(pg, "order_date")).isEqualTo("order_date");
        assertThat(LiveDdlWriter.ident(pg, "OrderDate")).isEqualTo("\"OrderDate\"");
        assertThat(LiveDdlWriter.ident(pg, "order")).isEqualTo("\"order\"");
        DialectSupport ora = DialectSupport.of(SqlDialect.ORACLE);
        assertThat(LiveDdlWriter.ident(ora, "ORDER_DATE")).isEqualTo("ORDER_DATE");
        assertThat(LiveDdlWriter.ident(ora, "order_date")).isEqualTo("\"order_date\"");
        DialectSupport ms = DialectSupport.of(SqlDialect.MSSQL);
        assertThat(LiveDdlWriter.ident(ms, "OrderDate")).isEqualTo("OrderDate");
        assertThat(LiveDdlWriter.ident(ms, "Order Date")).isEqualTo("\"Order Date\"");
        assertThat(LiveDdlWriter.ident(ms, "User")).isEqualTo("[User]");
    }

    @Test
    void aForeignKeyToATableNotReadStaysAComment() {
        DialectSupport pg = DialectSupport.of(SqlDialect.POSTGRESQL);
        Table t = new Table("public", "orders", Kind.TABLE,
                List.of(new Column("id", "int8", 19, 0, false, false), new Column("customer_id", "int8", 19, 0, true, false)),
                List.of("id"), List.of(new ForeignKey(List.of("customer_id"), "public", "customers", List.of("id"))),
                List.of(), List.of());
        String ddl = LiveDdlWriter.write(pg, new LiveSchemaModel.Schema("public", List.of(t), List.of("x\ny")), "db", false);
        assertThat(ddl).doesNotContain("ALTER TABLE")
                .contains("-- orders (customer_id) references public.customers, which was not read")
                .contains("-- Note: x y")
                .contains("CREATE TABLE orders (");
        assertThat(generator.parseTablesForImport(ddl, SqlDialect.POSTGRESQL)).hasSize(1);
    }

    @Test
    void typesEachDriverReports() {
        DialectSupport pg = DialectSupport.of(SqlDialect.POSTGRESQL);
        assertThat(pg.typeOf(col("numeric", 131089, 0))).isEqualTo("NUMERIC");
        assertThat(pg.typeOf(col("varchar", 2147483647, 0))).isEqualTo("VARCHAR");
        assertThat(pg.typeOf(col("_int4", 10, 0))).isEqualTo("TEXT");
        assertThat(pg.typeOf(col("bpchar", 3, 0))).isEqualTo("CHAR(3)");
        DialectSupport ora = DialectSupport.of(SqlDialect.ORACLE);
        assertThat(ora.typeOf(col("NUMBER", 0, -127))).isEqualTo("NUMBER");
        assertThat(ora.typeOf(col("NUMBER", 10, 0))).isEqualTo("NUMBER(10)");
        assertThat(ora.typeOf(col("TIMESTAMP(6)", 11, 6))).isEqualTo("TIMESTAMP");
        assertThat(ora.typeOf(col("SDO_GEOMETRY", 1, 0))).isEqualTo("VARCHAR2(4000)");
        DialectSupport ms = DialectSupport.of(SqlDialect.MSSQL);
        assertThat(ms.typeOf(col("int identity", 10, 0))).isEqualTo("INT");
        assertThat(ms.typeOf(col("varbinary", 2147483647, 0))).isEqualTo("VARBINARY(MAX)");
        assertThat(ms.typeOf(col("geography", 0, 0))).isEqualTo("NVARCHAR(MAX)");
        DialectSupport db2 = DialectSupport.of(SqlDialect.DB2);
        assertThat(db2.typeOf(col("CHAR () FOR BIT DATA", 16, 0))).isEqualTo("BINARY(16)");
        assertThat(db2.typeOf(col("VARCHAR () FOR BIT DATA", 40, 0))).isEqualTo("VARBINARY(40)");
        assertThat(db2.typeOf(col("DATALINK", 200, 0))).isEqualTo("VARCHAR(1000)");
    }

    private static Column col(String type, int size, int digits) {
        return new Column("c", type, size, digits, true, false);
    }

    @Test
    void urlsAreBuiltFromTheParts() {
        ConnectionSpec spec = new ConnectionSpec(SqlDialect.MSSQL, "sql01.menora.co.il", null, "Hr", null, "reader",
                "secret", true, "sql01/Hr");
        String url = DialectSupport.of(SqlDialect.MSSQL).url(spec);
        assertThat(url).startsWith("jdbc:sqlserver://sql01.menora.co.il:1433;databaseName=Hr;")
                .contains("trustServerCertificate=true").doesNotContain("secret");
        assertThat(DialectSupport.of(SqlDialect.ORACLE).url(new ConnectionSpec(SqlDialect.ORACLE, "ora", 1522, "HRPDB",
                null, "u", null, false, "x"))).isEqualTo("jdbc:oracle:thin:@//ora:1522/HRPDB");
        assertThat(DialectSupport.of(SqlDialect.DB2).url(new ConnectionSpec(SqlDialect.DB2, "as400", null, null,
                "HRLIB", "u", null, false, "x"))).isEqualTo("jdbc:as400://as400;libraries=HRLIB");
        assertThat(DialectSupport.of(SqlDialect.POSTGRESQL).properties(spec).getProperty("password")).isEqualTo("secret");
        assertThat(spec.toString()).doesNotContain("secret");
    }
}

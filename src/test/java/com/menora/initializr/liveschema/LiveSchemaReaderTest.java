package com.menora.initializr.liveschema;

import com.menora.initializr.liveschema.LiveSchemaModel.Column;
import com.menora.initializr.liveschema.LiveSchemaModel.Index;
import com.menora.initializr.liveschema.LiveSchemaModel.IndexColumn;
import com.menora.initializr.liveschema.LiveSchemaModel.Kind;
import com.menora.initializr.liveschema.LiveSchemaModel.Table;
import com.menora.initializr.sql.GeneratedJavaFile;
import com.menora.initializr.sql.SqlDepOptions;
import com.menora.initializr.sql.SqlDialect;
import com.menora.initializr.sql.SqlEntityGenerator;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The reader over a real catalog (an in-memory H2): what it takes beyond tables and keys —
 * indexes, column defaults, comments — and that its two ways of reading keys and indexes agree:
 * one catalog query per schema, and the driver asked table by table (what every read used to
 * do, and the fallback when a database refuses a query). The other databases' catalog queries
 * run in {@code LiveSchemaDockerTests}.
 */
class LiveSchemaReaderTest {

    private static final DialectSupport H2 = DialectSupport.of(SqlDialect.H2);
    private static final List<String> NAMES = List.of("CUSTOMERS", "ORDERS", "ORDER_LINES", "BIG_ORDERS");

    private static Connection db;

    @BeforeAll
    static void createDatabase() throws Exception {
        db = DriverManager.getConnection("jdbc:h2:mem:livereader;DB_CLOSE_DELAY=-1", "sa", "");
        try (Statement s = db.createStatement()) {
            s.execute("CREATE SCHEMA SHOP");
            s.execute("CREATE TABLE SHOP.CUSTOMERS (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "NAME VARCHAR(100) NOT NULL, STATUS VARCHAR(10) DEFAULT 'NEW' NOT NULL, CREDIT NUMERIC(10,2) DEFAULT 0, "
                    + "ACTIVE BOOLEAN DEFAULT TRUE, CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                    + "CODE VARCHAR(20) DEFAULT CURRENT_USER, CONSTRAINT UQ_CUSTOMER_NAME UNIQUE (NAME))");
            s.execute("CREATE TABLE SHOP.ORDERS (ID BIGINT PRIMARY KEY, CUSTOMER_ID BIGINT NOT NULL, PLACED DATE, "
                    + "TOTAL NUMERIC(12,2), CONSTRAINT FK_ORDER_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHOP.CUSTOMERS(ID))");
            s.execute("CREATE TABLE SHOP.ORDER_LINES (ORDER_ID BIGINT NOT NULL, LINE_NO INT NOT NULL, SKU VARCHAR(40), "
                    + "PRIMARY KEY (ORDER_ID, LINE_NO), FOREIGN KEY (ORDER_ID) REFERENCES SHOP.ORDERS(ID))");
            s.execute("CREATE INDEX IDX_ORDERS_PLACED ON SHOP.ORDERS (PLACED DESC, CUSTOMER_ID)");
            s.execute("CREATE UNIQUE INDEX UQ_LINE_SKU ON SHOP.ORDER_LINES (ORDER_ID, SKU)");
            s.execute("COMMENT ON TABLE SHOP.CUSTOMERS IS 'Who buys'");
            s.execute("COMMENT ON COLUMN SHOP.CUSTOMERS.NAME IS 'The customer''s trading name'");
            s.execute("CREATE VIEW SHOP.BIG_ORDERS AS SELECT ID, CUSTOMER_ID, TOTAL, PLACED FROM SHOP.ORDERS WHERE TOTAL > 1000");
        }
    }

    @AfterAll
    static void dropDatabase() throws Exception {
        try (Statement s = db.createStatement()) {
            s.execute("DROP ALL OBJECTS");
        }
        db.close();
    }

    private static Table table(LiveSchemaModel.Schema schema, String name) {
        return schema.tables().stream().filter(t -> t.name().equals(name)).findFirst().orElseThrow();
    }

    @Test
    void readsKeysIndexesDefaultsAndCommentsWithOneQueryPerSchema() throws Exception {
        LiveSchemaReader reader = new LiveSchemaReader(H2);
        LiveSchemaModel.Schema read = reader.read(db, "SHOP", NAMES);
        assertThat(read.warnings()).isEmpty();
        assertThat(reader.refusedQueries()).isEmpty();

        Table customers = table(read, "CUSTOMERS");
        assertThat(customers.primaryKey()).containsExactly("ID");
        assertThat(customers.uniqueKeys()).containsExactly(List.of("NAME"));
        assertThat(customers.indexes()).isEmpty();
        assertThat(customers.comment()).isEqualTo("Who buys");
        assertThat(customers.column("NAME").comment()).isEqualTo("The customer's trading name");
        assertThat(customers.column("STATUS").comment()).isNull();
        assertThat(customers.column("STATUS").defaultValue()).isEqualTo("'NEW'");
        assertThat(customers.column("CREDIT").defaultValue()).isEqualTo("0");
        assertThat(customers.column("ACTIVE").defaultValue()).isEqualTo("TRUE");
        assertThat(customers.column("CREATED").defaultValue()).isEqualTo("CURRENT_TIMESTAMP");
        assertThat(customers.column("CODE").defaultValue()).isEqualTo("CURRENT_USER");
        assertThat(customers.column("NAME").defaultValue()).isNull();

        Table orders = table(read, "ORDERS");
        assertThat(orders.foreignKeys()).singleElement().satisfies(fk -> {
            assertThat(fk.columns()).containsExactly("CUSTOMER_ID");
            assertThat(fk.referencedSchema()).isEqualTo("SHOP");
            assertThat(fk.referencedTable()).isEqualTo("CUSTOMERS");
            assertThat(fk.referencedColumns()).containsExactly("ID");
        });
        // Its own index — not the one H2 makes behind the foreign key.
        assertThat(orders.indexes()).containsExactly(new Index("IDX_ORDERS_PLACED", false,
                List.of(new IndexColumn("PLACED", true), new IndexColumn("CUSTOMER_ID", false)), null));

        Table lines = table(read, "ORDER_LINES");
        assertThat(lines.primaryKey()).containsExactly("ORDER_ID", "LINE_NO");
        assertThat(lines.uniqueKeys()).containsExactly(List.of("ORDER_ID", "SKU"));
        assertThat(lines.foreignKeys()).hasSize(1);

        Table view = table(read, "BIG_ORDERS");
        assertThat(view.kind()).isEqualTo(Kind.VIEW);
        assertThat(view.columns()).extracting(Column::name).containsExactly("ID", "CUSTOMER_ID", "TOTAL", "PLACED");
    }

    @Test
    void theDriverAskedTableByTableAnswersTheSame() throws Exception {
        LiveSchemaModel.Schema byQuery = new LiveSchemaReader(H2).read(db, "SHOP", NAMES);
        LiveSchemaModel.Schema byDriver = new LiveSchemaReader(H2, false).read(db, "SHOP", NAMES);
        assertThat(byDriver.warnings()).isEmpty();
        for (String name : NAMES) {
            Table a = table(byQuery, name);
            Table b = table(byDriver, name);
            assertThat(b.columns()).as(name).isEqualTo(a.columns());
            assertThat(b.primaryKey()).as(name).isEqualTo(a.primaryKey());
            assertThat(b.foreignKeys()).as(name).isEqualTo(a.foreignKeys());
            assertThat(b.uniqueKeys()).as(name).containsExactlyInAnyOrderElementsOf(a.uniqueKeys());
            assertThat(b.checks()).as(name).isEqualTo(a.checks());
            assertThat(b.comment()).as(name).isEqualTo(a.comment());
            // The driver cannot tell the indexes H2 makes for itself, so it has those too.
            assertThat(b.indexes()).as(name).containsAll(a.indexes());
        }
    }

    @Test
    void theScriptCarriesThemAndRunsOnAnEmptyDatabase() throws Exception {
        LiveSchemaModel.Schema read = new LiveSchemaReader(H2).read(db, "SHOP", NAMES);
        String script = LiveDdlWriter.write(H2, read, "localhost/livereader", true);
        assertThat(script)
                .contains("    STATUS VARCHAR(10) DEFAULT 'NEW' NOT NULL,\n")
                .contains("    CREDIT NUMERIC(10,2) DEFAULT 0,\n")
                .contains("    ACTIVE BOOLEAN DEFAULT TRUE,\n")
                .contains("    CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n")
                // An expression is not copied into the script: it says what the database has.
                .contains("    CODE VARCHAR(20), -- default in the database: CURRENT_USER\n")
                .contains("CREATE INDEX IDX_ORDERS_PLACED ON SHOP.ORDERS (PLACED DESC, CUSTOMER_ID);")
                .contains("COMMENT ON TABLE SHOP.CUSTOMERS IS 'Who buys';")
                .contains("COMMENT ON COLUMN SHOP.CUSTOMERS.NAME IS 'The customer''s trading name';")
                .contains("SELECT CAST(ID AS BIGINT) AS ID, CAST(CUSTOMER_ID AS BIGINT) AS CUSTOMER_ID, "
                        + "CAST(TOTAL AS NUMERIC(12,2)) AS TOTAL, CAST(PLACED AS DATE) AS PLACED FROM SHOP.BIG_ORDERS;");

        // Every statement of it but the view's SELECT is a migration: it runs as written.
        try (Connection empty = DriverManager.getConnection("jdbc:h2:mem:livereader-copy", "sa", "");
             Statement s = empty.createStatement()) {
            s.execute("CREATE SCHEMA SHOP");
            for (String statement : script.split(";\\n")) {
                String sql = statement.replaceAll("(?m)^--.*$", "").replaceAll("(?m) -- .*$", "").trim();
                if (sql.isEmpty() || sql.startsWith("SELECT")) continue;
                s.execute(sql);
            }
            LiveSchemaModel.Schema copy = new LiveSchemaReader(H2).read(empty, "SHOP", List.of("CUSTOMERS", "ORDERS", "ORDER_LINES"));
            assertThat(table(copy, "ORDERS").indexes()).isEqualTo(table(read, "ORDERS").indexes());
            assertThat(table(copy, "CUSTOMERS").comment()).isEqualTo("Who buys");
            assertThat(table(copy, "CUSTOMERS").column("STATUS").defaultValue()).isEqualTo("'NEW'");
        }

        // And the SQL wizard reads it: the index on the entity, the view's fields typed by their casts.
        List<GeneratedJavaFile> files = new SqlEntityGenerator().generate(script, SqlDialect.H2, "com.menora.demo",
                new SqlDepOptions("entity", List.of()));
        assertThat(file(files, "entity/Orders.java"))
                .contains("indexes = {@Index(name = \"IDX_ORDERS_PLACED\", columnList = \"PLACED DESC, CUSTOMER_ID\")}");
        assertThat(file(files, "entity/BigOrders.java"))
                .contains("private Long id;").contains("private Long customerId;")
                .contains("private BigDecimal total;").contains("private LocalDate placed;")
                .doesNotContain("TODO");
    }

    private static String file(List<GeneratedJavaFile> files, String suffix) {
        return files.stream().filter(f -> f.relativePath().endsWith(suffix)).findFirst().orElseThrow().content();
    }
}

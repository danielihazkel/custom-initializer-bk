package com.menora.initializr.liveschema;

import com.menora.initializr.sql.SqlDialect;

import java.util.List;
import java.util.Locale;
import java.util.Properties;
import java.util.Set;

/**
 * What differs per database when reading its schema: the driver and URL, the connection
 * properties that keep a read short and read-only, which schemas are the system's own, how a
 * column's type is written back as DDL the SQL wizard's parser reads, and where CHECK
 * constraints live.
 *
 * <p>Written against each driver's documentation; only H2 runs in the default build. PostgreSQL,
 * SQL Server and Oracle are exercised by {@code LiveSchemaDockerTests} ({@code -Dsmoke.docker=true});
 * DB2 for IBM i (jt400) has not been run against a server.
 */
public abstract class DialectSupport {

    /** Seconds a login may take, and a single catalog query. */
    static final int LOGIN_TIMEOUT_SECONDS = 10;
    static final int QUERY_TIMEOUT_SECONDS = 30;

    public abstract SqlDialect dialect();

    public abstract String driverClass();

    /** Null when the dialect has no port to name (DB2 for IBM i finds its own). */
    public abstract Integer defaultPort();

    abstract String url(ConnectionSpec c);

    /** User, password and the timeouts — the driver's own names for them. */
    abstract Properties properties(ConnectionSpec c);

    /** True for the database's own schemas (catalog, system, sample), left out of the list. */
    abstract boolean systemSchema(String name);

    /** How the database stores an unquoted name: lower (PostgreSQL), upper, or as written (SQL Server). */
    abstract String fold(String name);

    /**
     * A query listing the schema's CHECK constraints as {@code (table name, clause)} rows, one
     * {@code ?} for the schema; null when the dialect has none to offer.
     */
    abstract String checkQuery();

    /** A query listing the schema's identity columns as {@code (table, column)}; null when the driver says so itself. */
    String identityQuery() { return null; }

    /** A query listing the schemas a user may read, when the driver's own list is too wide; null otherwise. */
    String schemasQuery() { return null; }

    /** The column's type as DDL in this dialect, which {@code TypeMappers} maps to the same Java type. */
    public abstract String typeOf(LiveSchemaModel.Column column);

    /** How the column's identity is declared after its type. */
    String identityClause() { return "GENERATED BY DEFAULT AS IDENTITY"; }

    /** True when the driver reports {@code TYPE_NAME} as {@code "int identity"} (SQL Server). */
    boolean identityInTypeName(String typeName) { return false; }

    public static DialectSupport of(SqlDialect dialect) {
        return switch (dialect) {
            case POSTGRESQL -> new Postgres();
            case MSSQL -> new SqlServer();
            case ORACLE -> new Oracle();
            case DB2 -> new Db2ForI();
            case H2 -> new H2();
            case MYSQL -> throw LiveSchemaException.badRequest("MySQL cannot be read");
        };
    }

    /** The dialects a user can be offered (H2 only when a test turns it on). */
    public static final List<SqlDialect> READABLE = List.of(SqlDialect.POSTGRESQL, SqlDialect.MSSQL,
            SqlDialect.ORACLE, SqlDialect.DB2);

    public boolean driverPresent() {
        try {
            Class.forName(driverClass(), false, DialectSupport.class.getClassLoader());
            return true;
        } catch (ClassNotFoundException | LinkageError e) {
            return false;
        }
    }

    // ── Shared type writing ────────────────────────────────────────────────

    private static final Set<String> SIZED = Set.of("CHAR", "VARCHAR", "NCHAR", "NVARCHAR", "VARCHAR2", "NVARCHAR2",
            "CHARACTER", "GRAPHIC", "VARGRAPHIC", "BINARY", "VARBINARY", "RAW");
    private static final Set<String> DECIMAL = Set.of("NUMERIC", "DECIMAL", "DEC", "NUMBER");

    /** {@code VARCHAR} + 100 → {@code VARCHAR(100)}; a decimal type with its precision and scale. */
    static String withSize(String type, LiveSchemaModel.Column c, int maxLength) {
        String upper = type.toUpperCase(Locale.ROOT);
        if (SIZED.contains(upper)) {
            Integer n = c.size();
            return n != null && n > 0 && n <= maxLength ? upper + "(" + n + ")" : upper;
        }
        if (DECIMAL.contains(upper)) {
            Integer p = c.size();
            Integer s = c.digits();
            if (p == null || p <= 0 || p > 1000) return upper;
            return s != null && s > 0 && s <= p ? upper + "(" + p + "," + s + ")" : upper + "(" + p + ")";
        }
        return upper;
    }

    /** A type name the parser can take as it is: words only. Anything else reads as text. */
    static String plainOr(String type, String fallback) {
        return type != null && type.matches("[A-Za-z][A-Za-z0-9_ ]*") ? type.toUpperCase(Locale.ROOT) : fallback;
    }

    static Properties userAndPassword(ConnectionSpec c) {
        Properties p = new Properties();
        p.setProperty("user", c.user());
        if (c.password() != null) p.setProperty("password", c.password());
        return p;
    }

    static int portOf(ConnectionSpec c, int fallback) {
        return c.port() != null ? c.port() : fallback;
    }

    // ── PostgreSQL ─────────────────────────────────────────────────────────

    static final class Postgres extends DialectSupport {
        @Override public SqlDialect dialect() { return SqlDialect.POSTGRESQL; }
        @Override public String driverClass() { return "org.postgresql.Driver"; }
        @Override public Integer defaultPort() { return 5432; }

        @Override String url(ConnectionSpec c) {
            return "jdbc:postgresql://" + c.host() + ":" + portOf(c, 5432) + "/" + c.database();
        }

        @Override Properties properties(ConnectionSpec c) {
            Properties p = userAndPassword(c);
            p.setProperty("connectTimeout", String.valueOf(LOGIN_TIMEOUT_SECONDS));
            p.setProperty("loginTimeout", String.valueOf(LOGIN_TIMEOUT_SECONDS));
            p.setProperty("socketTimeout", String.valueOf(QUERY_TIMEOUT_SECONDS * 2));
            p.setProperty("readOnly", "true");
            p.setProperty("ApplicationName", "menora-initializr schema reader");
            return p;
        }

        @Override boolean systemSchema(String name) {
            String n = name.toLowerCase(Locale.ROOT);
            return n.equals("information_schema") || n.equals("pg_catalog") || n.startsWith("pg_toast")
                    || n.startsWith("pg_temp");
        }

        @Override String fold(String name) { return name.toLowerCase(Locale.ROOT); }

        @Override String checkQuery() {
            return "SELECT c.relname, pg_get_constraintdef(k.oid) FROM pg_constraint k "
                    + "JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace "
                    + "WHERE k.contype = 'c' AND n.nspname = ?";
        }

        /** An enum type's labels in order, so a column of that type reads as an enum. */
        static final String ENUM_QUERY = "SELECT t.typname, e.enumlabel FROM pg_type t "
                + "JOIN pg_enum e ON e.enumtypid = t.oid ORDER BY t.typname, e.enumsortorder";

        @Override public String typeOf(LiveSchemaModel.Column c) {
            String t = c.typeName() == null ? "" : c.typeName().toLowerCase(Locale.ROOT);
            return switch (t) {
                case "int8", "bigserial" -> "BIGINT";
                case "int4", "serial" -> "INTEGER";
                case "int2", "smallserial" -> "SMALLINT";
                case "bpchar" -> withSize("CHAR", c, 10_485_760);
                case "varchar" -> withSize("VARCHAR", c, 10_485_760);
                case "text", "citext", "name" -> "TEXT";
                case "numeric" -> withSize("NUMERIC", c, 1000);
                case "float8" -> "DOUBLE PRECISION";
                case "float4" -> "REAL";
                case "bool" -> "BOOLEAN";
                case "date" -> "DATE";
                case "time", "timetz" -> "TIME";
                case "timestamp" -> "TIMESTAMP";
                case "timestamptz" -> "TIMESTAMPTZ";
                case "uuid" -> "UUID";
                case "bytea" -> "BYTEA";
                case "json" -> "JSON";
                case "jsonb" -> "JSONB";
                // Arrays (_int4), ranges, user types: text is what the generated code can hold.
                default -> "TEXT";
            };
        }
    }

    // ── SQL Server ─────────────────────────────────────────────────────────

    static final class SqlServer extends DialectSupport {
        @Override public SqlDialect dialect() { return SqlDialect.MSSQL; }
        @Override public String driverClass() { return "com.microsoft.sqlserver.jdbc.SQLServerDriver"; }
        @Override public Integer defaultPort() { return 1433; }

        @Override String url(ConnectionSpec c) {
            return "jdbc:sqlserver://" + c.host() + ":" + portOf(c, 1433) + ";databaseName=" + c.database()
                    + ";encrypt=true;trustServerCertificate=" + c.trustServerCertificate()
                    + ";applicationIntent=ReadOnly;loginTimeout=" + LOGIN_TIMEOUT_SECONDS
                    + ";socketTimeout=" + QUERY_TIMEOUT_SECONDS * 2000
                    + ";applicationName=menora-initializr";
        }

        @Override Properties properties(ConnectionSpec c) { return userAndPassword(c); }

        private static final Set<String> SYSTEM = Set.of("sys", "information_schema", "guest", "db_owner",
                "db_accessadmin", "db_securityadmin", "db_ddladmin", "db_backupoperator", "db_datareader",
                "db_datawriter", "db_denydatareader", "db_denydatawriter");

        @Override boolean systemSchema(String name) { return SYSTEM.contains(name.toLowerCase(Locale.ROOT)); }

        @Override String fold(String name) { return name; }

        @Override String checkQuery() {
            return "SELECT t.name, cc.definition FROM sys.check_constraints cc "
                    + "JOIN sys.tables t ON t.object_id = cc.parent_object_id "
                    + "JOIN sys.schemas s ON s.schema_id = t.schema_id WHERE s.name = ?";
        }

        @Override boolean identityInTypeName(String typeName) {
            return typeName != null && typeName.toLowerCase(Locale.ROOT).endsWith(" identity");
        }

        @Override String identityClause() { return "IDENTITY(1,1)"; }

        @Override public String typeOf(LiveSchemaModel.Column c) {
            String t = c.typeName() == null ? "" : c.typeName().toLowerCase(Locale.ROOT).replace(" identity", "").trim();
            return switch (t) {
                // (max): COLUMN_SIZE is 2^31-1 (varchar) or 2^30-1 (nvarchar).
                case "varchar", "nvarchar", "varbinary" -> c.size() != null && c.size() > 8000
                        ? t.toUpperCase(Locale.ROOT) + "(MAX)" : withSize(t, c, 8000);
                case "char", "nchar", "binary" -> withSize(t, c, 8000);
                case "decimal", "numeric" -> withSize(t, c, 38);
                case "int", "bigint", "smallint", "tinyint", "bit", "money", "smallmoney", "float", "real",
                     "date", "time", "datetime", "datetime2", "smalldatetime", "datetimeoffset",
                     "uniqueidentifier", "text", "ntext", "image", "xml" -> t.toUpperCase(Locale.ROOT);
                default -> "NVARCHAR(MAX)";
            };
        }
    }

    // ── Oracle ─────────────────────────────────────────────────────────────

    static final class Oracle extends DialectSupport {
        @Override public SqlDialect dialect() { return SqlDialect.ORACLE; }
        @Override public String driverClass() { return "oracle.jdbc.OracleDriver"; }
        @Override public Integer defaultPort() { return 1521; }

        @Override String url(ConnectionSpec c) {
            return "jdbc:oracle:thin:@//" + c.host() + ":" + portOf(c, 1521) + "/" + c.database();
        }

        @Override Properties properties(ConnectionSpec c) {
            Properties p = userAndPassword(c);
            p.setProperty("oracle.net.CONNECT_TIMEOUT", String.valueOf(LOGIN_TIMEOUT_SECONDS * 1000));
            p.setProperty("oracle.jdbc.ReadTimeout", String.valueOf(QUERY_TIMEOUT_SECONDS * 2000));
            p.setProperty("v$session.program", "menora-initializr");
            return p;
        }

        private static final Set<String> SYSTEM = Set.of("SYS", "SYSTEM", "OUTLN", "XDB", "DBSNMP", "APPQOSSYS",
                "AUDSYS", "CTXSYS", "DVSYS", "GSMADMIN_INTERNAL", "LBACSYS", "MDSYS", "OJVMSYS", "OLAPSYS",
                "ORDDATA", "ORDSYS", "WMSYS", "ANONYMOUS", "GSMCATUSER", "GSMUSER", "SYSBACKUP", "SYSDG",
                "SYSKM", "SYSRAC", "REMOTE_SCHEDULER_AGENT", "DIP", "XS$NULL", "DBSFWUSER", "GGSYS",
                "MDDATA", "ORACLE_OCM", "SI_INFORMTN_SCHEMA", "ORDPLUGINS", "PUBLIC");

        @Override boolean systemSchema(String name) {
            String n = name.toUpperCase(Locale.ROOT);
            return SYSTEM.contains(n) || n.startsWith("APEX_") || n.startsWith("FLOWS_");
        }

        @Override String fold(String name) { return name.toUpperCase(Locale.ROOT); }

        /** 12c and later mark the users Oracle installed; earlier versions fall back to the driver's list. */
        @Override String schemasQuery() {
            return "SELECT username FROM all_users WHERE oracle_maintained = 'N' ORDER BY username";
        }

        @Override String checkQuery() {
            return "SELECT table_name, search_condition FROM all_constraints "
                    + "WHERE owner = ? AND constraint_type = 'C'";
        }

        @Override String identityQuery() {
            return "SELECT table_name, column_name FROM all_tab_identity_cols WHERE owner = ?";
        }

        @Override public String typeOf(LiveSchemaModel.Column c) {
            String t = c.typeName() == null ? "" : c.typeName().toUpperCase(Locale.ROOT)
                    .replaceAll("\\(\\d+\\)", "").trim();
            return switch (t) {
                case "NUMBER" -> {
                    // NUMBER without precision: size 0, scale -127 (a FLOAT reads the same way).
                    Integer p = c.size();
                    Integer s = c.digits();
                    if (p == null || p <= 0) yield "NUMBER";
                    if (s != null && s == -127) yield "FLOAT";
                    yield withSize("NUMBER", c, 38);
                }
                case "VARCHAR2", "NVARCHAR2", "CHAR", "NCHAR", "RAW" -> withSize(t, c, 32767);
                case "TIMESTAMP WITH TIME ZONE", "TIMESTAMP WITH LOCAL TIME ZONE", "TIMESTAMP", "DATE",
                     "CLOB", "NCLOB", "BLOB", "FLOAT", "BINARY_FLOAT", "BINARY_DOUBLE", "LONG" -> t;
                default -> "VARCHAR2(4000)";
            };
        }
    }

    // ── DB2 for IBM i (jt400) ──────────────────────────────────────────────

    static final class Db2ForI extends DialectSupport {
        @Override public SqlDialect dialect() { return SqlDialect.DB2; }
        @Override public String driverClass() { return "com.ibm.as400.access.AS400JDBCDriver"; }
        @Override public Integer defaultPort() { return null; }

        @Override String url(ConnectionSpec c) {
            StringBuilder url = new StringBuilder("jdbc:as400://").append(c.host());
            if (c.library() != null && !c.library().isBlank()) url.append(";libraries=").append(c.library().trim());
            return url.toString();
        }

        @Override Properties properties(ConnectionSpec c) {
            Properties p = userAndPassword(c);
            p.setProperty("prompt", "false");
            p.setProperty("naming", "sql");
            p.setProperty("access", "read only");
            p.setProperty("login timeout", String.valueOf(LOGIN_TIMEOUT_SECONDS));
            p.setProperty("socket timeout", String.valueOf(QUERY_TIMEOUT_SECONDS * 2000));
            return p;
        }

        @Override boolean systemSchema(String name) {
            String n = name.toUpperCase(Locale.ROOT);
            return (n.startsWith("Q") && !n.equals("QGPL")) || n.startsWith("SYS") || n.startsWith("#");
        }

        @Override String fold(String name) { return name.toUpperCase(Locale.ROOT); }

        @Override String checkQuery() {
            return "SELECT c.TABLE_NAME, k.CHECK_CLAUSE FROM QSYS2.SYSCST c JOIN QSYS2.SYSCHKCST k "
                    + "ON k.CONSTRAINT_SCHEMA = c.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME = c.CONSTRAINT_NAME "
                    + "WHERE c.TABLE_SCHEMA = ? AND c.CONSTRAINT_TYPE = 'CHECK'";
        }

        @Override public String typeOf(LiveSchemaModel.Column c) {
            String t = c.typeName() == null ? "" : c.typeName().toUpperCase(Locale.ROOT).trim();
            if (t.contains("FOR BIT DATA")) {
                return withSize(t.startsWith("VARCHAR") ? "VARBINARY" : "BINARY", c, 32740);
            }
            return switch (t) {
                case "CHAR", "VARCHAR", "GRAPHIC", "VARGRAPHIC", "BINARY", "VARBINARY" -> withSize(t, c, 32740);
                case "DECIMAL", "NUMERIC" -> withSize(t, c, 63);
                case "INTEGER", "BIGINT", "SMALLINT", "DATE", "TIME", "TIMESTAMP", "CLOB", "DBCLOB", "BLOB",
                     "REAL", "DOUBLE", "FLOAT", "BOOLEAN" -> t;
                default -> withSize("VARCHAR", new LiveSchemaModel.Column(c.name(), "VARCHAR", 1000, null,
                        c.nullable(), false), 32740);
            };
        }
    }

    // ── H2 (tests only: menora.live-schema.allow-h2) ───────────────────────

    static final class H2 extends DialectSupport {
        @Override public SqlDialect dialect() { return SqlDialect.H2; }
        @Override public String driverClass() { return "org.h2.Driver"; }
        @Override public Integer defaultPort() { return null; }

        /** An in-memory database by name only — never a file, never a server. */
        @Override String url(ConnectionSpec c) { return "jdbc:h2:mem:" + c.database() + ";IFEXISTS=TRUE"; }

        @Override Properties properties(ConnectionSpec c) { return userAndPassword(c); }

        @Override boolean systemSchema(String name) { return name.equalsIgnoreCase("INFORMATION_SCHEMA"); }

        @Override String fold(String name) { return name.toUpperCase(Locale.ROOT); }

        @Override String checkQuery() {
            return "SELECT tc.TABLE_NAME, cc.CHECK_CLAUSE FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc "
                    + "JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc ON cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA "
                    + "AND cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME "
                    + "WHERE tc.TABLE_SCHEMA = ? AND tc.CONSTRAINT_TYPE = 'CHECK'";
        }

        @Override public String typeOf(LiveSchemaModel.Column c) {
            String t = c.typeName() == null ? "" : c.typeName().toUpperCase(Locale.ROOT);
            return switch (t) {
                case "CHARACTER VARYING" -> withSize("VARCHAR", c, 1_000_000_000);
                case "CHARACTER" -> withSize("CHAR", c, 1_000_000_000);
                case "CHARACTER LARGE OBJECT" -> "CLOB";
                case "BINARY LARGE OBJECT" -> "BLOB";
                case "NUMERIC", "DECIMAL" -> withSize(t, c, 100_000);
                case "TIMESTAMP WITH TIME ZONE" -> "TIMESTAMP WITH TIME ZONE";
                case "ENUM" -> "VARCHAR(255)";
                default -> plainOr(t, "VARCHAR(255)");
            };
        }
    }
}

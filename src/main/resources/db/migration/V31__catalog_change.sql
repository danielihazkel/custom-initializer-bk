-- V31: the catalog's change log (2026-11, admin identity and catalog history).
--
-- One row per catalog row created, changed or deleted, written in the same transaction as the
-- change by CatalogHistoryRecorder: who (the signed-in admin, or "system"), why (source: admin,
-- import, catalog-sync, template-reset, release-sync, restore, system), which request it was part
-- of (request_id: an import's hundreds of rows share one), and the row before and after as JSON.

CREATE TABLE admin_catalog_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at TIMESTAMP NOT NULL,
    actor VARCHAR(255) NOT NULL,
    source VARCHAR(32) NOT NULL,
    request_id VARCHAR(36) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    table_name VARCHAR(64) NOT NULL,
    row_id VARCHAR(64) NOT NULL,
    action VARCHAR(8) NOT NULL,
    label VARCHAR(255),
    before_json CLOB,
    after_json CLOB,
    changed_fields VARCHAR(1024)
);

CREATE INDEX idx_catalog_change_row ON admin_catalog_change (entity_type, row_id);
CREATE INDEX idx_catalog_change_request ON admin_catalog_change (request_id);
CREATE INDEX idx_catalog_change_at ON admin_catalog_change (changed_at);

-- V24: Design kits — the visual side of the fullstack frontend (tokens, fonts, assets, kit CSS),
-- versioned draft → published. See DESIGN_STUDIO_PLAN.md at the monorepo root.

CREATE TABLE initializer_design_kit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_key VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    -- The frontend template set the kit restyles (its glue and its components).
    base_set_key VARCHAR(100) NOT NULL,
    built_in BOOLEAN NOT NULL DEFAULT FALSE,
    default_palette_id VARCHAR(50),
    -- "<kit>@<version>" a clone started from; informational.
    cloned_from VARCHAR(80),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0,
    created_by VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_design_kit_key UNIQUE (kit_key)
);

CREATE TABLE initializer_design_kit_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id BIGINT NOT NULL,
    -- Null while a draft; 1, 2, … once published. A published row never changes again.
    version INT,
    status VARCHAR(20) NOT NULL,
    -- 1 on the kit's draft, NULL otherwise: with the unique key below, at most one draft per kit.
    draft_marker INT,
    based_on_version INT,
    contract_version INT NOT NULL,
    tokens CLOB NOT NULL,
    manifest CLOB NOT NULL,
    checksum VARCHAR(64),
    notes VARCHAR(1000),
    created_by VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    published_by VARCHAR(255),
    published_at TIMESTAMP,
    CONSTRAINT fk_design_kit_version_kit FOREIGN KEY (kit_id) REFERENCES initializer_design_kit (id) ON DELETE CASCADE,
    CONSTRAINT uk_design_kit_version UNIQUE (kit_id, version),
    CONSTRAINT uk_design_kit_draft UNIQUE (kit_id, draft_marker)
);

-- Text files a kit version ships: in P1 only its kit CSS; component slots and helpers later.
CREATE TABLE initializer_design_kit_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    path VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    content CLOB NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    CONSTRAINT fk_design_kit_file_version FOREIGN KEY (version_id) REFERENCES initializer_design_kit_version (id) ON DELETE CASCADE,
    CONSTRAINT uk_design_kit_file_path UNIQUE (version_id, path)
);

-- Binary content, stored once per distinct content (a new draft copies references, not bytes).
CREATE TABLE initializer_design_asset_blob (
    sha256 VARCHAR(64) PRIMARY KEY,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    content BLOB NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE initializer_design_kit_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    -- Path in the generated frontend: public/** or src/assets/**.
    target_path VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    blob_sha256 VARCHAR(64) NOT NULL,
    -- JSON: a font's family/weight/style, an image's alt text.
    meta VARCHAR(1000),
    CONSTRAINT fk_design_kit_asset_version FOREIGN KEY (version_id) REFERENCES initializer_design_kit_version (id) ON DELETE CASCADE,
    CONSTRAINT fk_design_kit_asset_blob FOREIGN KEY (blob_sha256) REFERENCES initializer_design_asset_blob (sha256),
    CONSTRAINT uk_design_kit_asset_path UNIQUE (version_id, target_path)
);

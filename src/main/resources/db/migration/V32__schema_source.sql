-- V32: databases an admin lets everyone read the schema of (2026-11, SQL wizard from a live database).
--
-- A source is named by its parts, never by a JDBC URL: the reader builds the URL, so no driver
-- property can be slipped in. The password is not stored: password_ref names the environment
-- variable (SCHEMA_SOURCE_...) or property (menora.live-schema.secrets....) that holds it.

CREATE TABLE initializer_schema_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    dialect VARCHAR(16) NOT NULL,
    host VARCHAR(253) NOT NULL,
    port INTEGER,
    database_name VARCHAR(128),
    library VARCHAR(128),
    username VARCHAR(128) NOT NULL,
    password_ref VARCHAR(255),
    trust_server_certificate BOOLEAN DEFAULT FALSE NOT NULL,
    default_schema VARCHAR(128),
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    sort_order INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT uq_schema_source_name UNIQUE (name)
);

-- Backend-tab setups saved for the whole team (the Backend tab's "Team" presets): the tab's
-- whole state — form, dependencies, sub-options, modules, wizard documents — kept verbatim.

CREATE TABLE initializer_backend_preset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    snapshot CLOB NOT NULL,
    coordinates VARCHAR(300),
    dependency_count INTEGER NOT NULL,
    module_count INTEGER NOT NULL,
    created_by VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_backend_preset_name UNIQUE (name)
);

CREATE INDEX idx_backend_preset_updated_at ON initializer_backend_preset (updated_at);

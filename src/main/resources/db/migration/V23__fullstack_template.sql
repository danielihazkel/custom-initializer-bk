-- V23: Team-shared layout-designer templates — a page or a dashboard widget, saved for everyone

CREATE TABLE initializer_fullstack_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    content CLOB NOT NULL,
    created_by VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_fullstack_template_kind_name UNIQUE (kind, name)
);

CREATE INDEX idx_fullstack_template_updated_at ON initializer_fullstack_template (updated_at);
